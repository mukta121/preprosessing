# 4. EXTRACT METADATA FROM DOCUMENT
# ============================================================

def extract_document_metadata(text, file_path):
    """
    Extract useful metadata from SOB documents.

    Attempts to find:
    - document_id
    - plan_name
    - state
    - effective_date
    - form_number
    - page header ID

    Missing information is stored as None.
    """

    metadata = {
        "document_id": get_document_id(file_path),
        "source_file": file_path.name,
        "plan_name": None,
        "state": None,
        "effective_date": None,
        "form_number": None,
        "page_header_id": None,
    }

    # --------------------------------------------------------
    # Page Header
    #
    # Example:
    # <!-- PageHeader="ID: MD0000003920_AE2 X" -->
    # --------------------------------------------------------

    match = re.search(
        r'PageHeader\s*=\s*"([^"]+)"',
        text,
        flags=re.IGNORECASE
    )

    if match:
        metadata["page_header_id"] = match.group(1).strip()


    # --------------------------------------------------------
    # Effective Date
    #
    # Example:
    # EFFECTIVE DATE: 01/01/2026
    # --------------------------------------------------------

    match = re.search(
        r"EFFECTIVE\s+DATE\s*:\s*"
        r"(\d{1,2}/\d{1,2}/\d{4})",
        text,
        flags=re.IGNORECASE
    )

    if match:
        metadata["effective_date"] = match.group(1)


    # --------------------------------------------------------
    # Form Number
    #
    # Example:
    # FORM #1574_16
    # --------------------------------------------------------

    match = re.search(
        r"FORM\s*#?\s*([A-Za-z0-9_\-]+)",
        text,
        flags=re.IGNORECASE
    )

    if match:
        metadata["form_number"] = match.group(1).strip()


    # --------------------------------------------------------
    # Try to infer plan name and state from front matter
    # --------------------------------------------------------

    first_lines = []

    for line in text.splitlines()[:50]:

        clean_line = line.strip()

        if not clean_line:
            continue

        if clean_line.startswith("<!--"):
            continue

        if clean_line.startswith("#"):
            continue

        first_lines.append(clean_line)


    # --------------------------------------------------------
    # Typical plan names
    # --------------------------------------------------------

    plan_keywords = [
        "HMO",
        "PPO",
        "LP",
        "POS",
        "EPO",
    ]

    for line in first_lines:

        upper_line = line.upper()

        if any(
            keyword in upper_line
            for keyword in plan_keywords
        ):

            # Avoid very long paragraphs
            if len(line) < 150:

                metadata["plan_name"] = line

                break


    # --------------------------------------------------------
    # State detection
    # --------------------------------------------------------

    states = [
        "MAINE",
        "MASSACHUSETTS",
        "NEW HAMPSHIRE",
        "RHODE ISLAND",
        "CONNECTICUT",
    ]

    for line in first_lines:

        normalized = line.upper().strip()

        for state in states:

            if normalized == state:

                metadata["state"] = state.title()

                break

        if metadata["state"]:
            break


    return metadata


