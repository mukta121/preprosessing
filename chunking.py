# 13. PROCESS ALL MARKDOWN FILES
# ============================================================

def process_all_files():

    md_files = sorted(
        SOURCE_DIR.glob("*.md")
    )


    print(
        "=" * 75
    )

    print(
        "POINT32HEALTH SOB CHUNKING PIPELINE"
    )

    print(
        "=" * 75
    )

    print(
        f"\nSource:"
    )

    print(
        SOURCE_DIR
    )

    print(
        f"\nOutput:"
    )

    print(
        OUTPUT_JSONL
    )

    print(
        f"\nMarkdown files found: "
        f"{len(md_files)}"
    )


    if not md_files:

        print(
            "\nNo Markdown files found."
        )

        return


    total_chunks = 0

    successful_files = 0

    failed_files = 0


    # --------------------------------------------------------
    # Open JSONL once and append every document's chunks
    # --------------------------------------------------------

    with OUTPUT_JSONL.open(
        "w",
        encoding="utf-8"
    ) as output_file:


        for file_path in md_files:

            try:

                print(
                    "\n" + "-" * 75
                )

                print(
                    f"Processing: "
                    f"{file_path.name}"
                )


                chunks = chunk_document(
                    file_path
                )


                for chunk in chunks:

                    output_file.write(
                        json.dumps(
                            chunk,
                            ensure_ascii=False
                        )
                        + "\n"
                    )


                print(
                    f"Created "
                    f"{len(chunks)} chunks"
                )


                text_chunks = sum(
                    1
                    for chunk in chunks
                    if chunk[
                        "chunk_type"
                    ] == "text"
                )


                table_chunks = sum(
                    1
                    for chunk in chunks
                    if chunk[
                        "chunk_type"
                    ] == "table"
                )


                print(
                    f"    Text chunks  : "
                    f"{text_chunks}"
                )

                print(
                    f"    Table chunks : "
                    f"{table_chunks}"
                )


                total_chunks += len(
                    chunks
                )

                successful_files += 1


            except Exception as e:

                failed_files += 1

                print(
                    f"ERROR processing "
                    f"{file_path.name}"
                )

                print(
                    f"{type(e).__name__}: {e}"
                )


    # ========================================================
    # FINAL SUMMARY
    # ========================================================

    print(
        "\n" + "=" * 75
    )

    print(
        "CHUNKING COMPLETE"
    )

    print(
        "=" * 75
    )


    print(
        f"Files processed successfully : "
        f"{successful_files}"
    )

    print(
        f"Files failed                 : "
        f"{failed_files}"
    )

    print(
        f"Total chunks created         : "
        f"{total_chunks}"
    )

    print(
        "\nJSONL saved to:"
    )

    print(
        OUTPUT_JSONL
    )


# ============================================================
# 14. ENTRY POINT
# ============================================================

if __name__ == "__main__":

    process_all_files()