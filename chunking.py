# 10. SPLIT MARKDOWN TABLES
# ============================================================

def split_table_section(
    text,
    max_chars=MAX_CHARS
):
    """
    Preserve small tables.

    For large Markdown tables:
    - preserve table header
    - split rows into smaller chunks
    """

    text = text.strip()

    if len(text) <= max_chars:

        return [text]


    lines = [
        line
        for line in text.splitlines()
        if line.strip()
    ]


    # --------------------------------------------------------
    # If it does not look like a Markdown table,
    # fall back to normal splitting
    # --------------------------------------------------------

    table_lines = [
        line
        for line in lines
        if "|" in line
    ]

    if len(table_lines) < 2:

        return split_text_section(
            text,
            max_chars=max_chars,
            overlap_chars=0
        )


    # --------------------------------------------------------
    # Assume first two table lines are:
    #
    # header
    # separator
    # --------------------------------------------------------

    header_lines = table_lines[:2]

    data_lines = table_lines[2:]


    header = "\n".join(
        header_lines
    )


    chunks = []

    current_rows = []


    for row in data_lines:

        candidate_rows = (
            current_rows
            + [row]
        )

        candidate = (
            header
            + "\n"
            + "\n".join(
                candidate_rows
            )
        )


        if len(candidate) <= max_chars:

            current_rows.append(row)

        else:

            if current_rows:

                chunks.append(
                    header
                    + "\n"
                    + "\n".join(
                        current_rows
                    )
                )

            current_rows = [row]


    if current_rows:

        chunks.append(
            header
            + "\n"
            + "\n".join(
                current_rows
            )
        )


    return chunks


