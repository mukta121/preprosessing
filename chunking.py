# 8. CHECK IF SECTION IS TABLE
# ============================================================

def is_table_section(section):
    """
    Identify extracted table sections.
    """

    values = [
        section.get("h1"),
        section.get("h2"),
        section.get("h3"),
        section.get("h4"),
        section.get("title"),
    ]

    values = [
        value.lower()
        for value in values
        if value
    ]

    # Extracted tables
    if any(
        "extracted tables" in value
        for value in values
    ):
        return True

    # Table 1, Table 2 etc.
    if any(
        re.search(
            r"\btable\s+\d+",
            value,
            flags=re.IGNORECASE
        )
        for value in values
    ):
        return True

    return False


