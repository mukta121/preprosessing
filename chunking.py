# 11. CREATE EMBEDDING TEXT
# ============================================================

def create_embedding_text(
    section_path,
    chunk_text,
    metadata
):
    """
    Add meaningful document context before the chunk.

    This is useful when generating embeddings later.
    """

    context = []

    if metadata.get("plan_name"):

        context.append(
            f"Plan: {metadata['plan_name']}"
        )

    if metadata.get("state"):

        context.append(
            f"State: {metadata['state']}"
        )

    if metadata.get("effective_date"):

        context.append(
            f"Effective Date: {metadata['effective_date']}"
        )

    if section_path:

        context.append(
            f"Section: {section_path}"
        )


    context_text = "\n".join(
        context
    )


    if context_text:

        return (
            context_text
            + "\n\n"
            + chunk_text
        )


    return chunk_text


