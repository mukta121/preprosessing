# 9. SPLIT TEXT AT PARAGRAPH BOUNDARIES
# ============================================================

def split_text_section(
    text,
    max_chars=MAX_CHARS,
    overlap_chars=OVERLAP_CHARS
):
    """
    Split large text sections while attempting to preserve
    paragraph boundaries.

    Small sections remain as one chunk.
    """

    text = text.strip()

    if len(text) <= max_chars:

        return [text]


    paragraphs = re.split(
        r"\n\s*\n",
        text
    )

    chunks = []

    current_chunk = ""


    for paragraph in paragraphs:

        paragraph = paragraph.strip()

        if not paragraph:
            continue


        # ----------------------------------------------------
        # Paragraph itself is too large
        # ----------------------------------------------------

        if len(paragraph) > max_chars:

            # Save existing chunk
            if current_chunk:

                chunks.append(
                    current_chunk.strip()
                )

                current_chunk = ""


            start = 0

            while start < len(paragraph):

                end = start + max_chars

                piece = paragraph[
                    start:end
                ].strip()

                if piece:

                    chunks.append(piece)

                start = (
                    end - overlap_chars
                )

            continue


        # ----------------------------------------------------
        # Try adding paragraph to current chunk
        # ----------------------------------------------------

        candidate = (
            current_chunk
            + "\n\n"
            + paragraph
        ).strip()


        if len(candidate) <= max_chars:

            current_chunk = candidate

        else:

            if current_chunk:

                chunks.append(
                    current_chunk.strip()
                )


            # -----------------------------------------------
            # Add overlap from previous chunk
            # -----------------------------------------------

            overlap = ""

            if chunks and overlap_chars > 0:

                previous = chunks[-1]

                overlap = previous[
                    -overlap_chars:
                ]

                # Try beginning overlap at word boundary
                first_space = overlap.find(" ")

                if first_space != -1:

                    overlap = overlap[
                        first_space + 1:
                    ]


            current_chunk = (
                overlap
                + "\n\n"
                + paragraph
            ).strip()


    if current_chunk:

        chunks.append(
            current_chunk.strip()
        )


    return chunks


