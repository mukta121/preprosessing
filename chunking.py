# 7. BUILD SECTION PATH
# ============================================================

def build_section_path(section):
    """
    Example:

    DOCUMENT TEXT
        >
    Covered Benefits
        >
    Durable Medical Equipment
    """

    parts = []

    for key in [
        "h1",
        "h2",
        "h3",
        "h4"
    ]:

        value = section.get(key)

        if (
            value
            and value not in parts
        ):

            parts.append(value)

    if not parts:

        parts.append(
            section.get(
                "title",
                "Front Matter"
            )
        )

    return " > ".join(parts)


