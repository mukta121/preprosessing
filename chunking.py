# 5. HEADING DETECTION
# ============================================================

def parse_heading(line):
    """
    Detect Markdown headings.

    Returns:
        heading_level
        heading_text

    Example:
        ## Covered Benefits

    returns:
        2, "Covered Benefits"
    """

    match = re.match(
        r"^(#{1,6})\s+(.+?)\s*$",
        line
    )

    if not match:
        return None

    level = len(
        match.group(1)
    )

    title = match.group(2).strip()

    return level, title


