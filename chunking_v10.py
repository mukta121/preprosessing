# 8. BUILD SECTION PATH
# ============================================================

def build_section_path(section):
    """
    Example output:

    DOCUMENT TEXT > Covered Benefits > HPHC
    """

    parts = []

    for key in [
        "h1",
        "h2",
        "h3",
        "h4",
    ]:

        value = section.get(key)

        if value and value not in parts:

            parts.append(
                value
            )


    if not parts:

        title = section.get(
            "title"
        )

        if title:

            parts.append(
                title
            )


    return " > ".join(parts)


