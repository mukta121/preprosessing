# 6. PARSE MARKDOWN HEADING
# ============================================================

def parse_heading(line):
    """
    Parse Markdown headings.

    Example:

    ## Covered Benefits

    returns:

    (2, "Covered Benefits")
    """

    match = re.match(
        r"^(#{1,6})\s+(.+?)\s*$",
        line
    )

    if not match:
        return None

    level = len(
        match.group(1)
    )

    title = (
        match.group(2).strip()
    )

    return level, title


