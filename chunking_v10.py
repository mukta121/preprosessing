# 7. PARSE DOCUMENT INTO HIERARCHICAL SECTIONS
# ============================================================

def parse_markdown_sections(text):
    """
    Convert Markdown document into sections while preserving
    heading hierarchy.

    Example:

    # DOCUMENT TEXT
    ## Covered Benefits
    ### HPHC
    #### Durable Medical Equipment

    The section hierarchy is preserved as:

    h1
    h2
    h3
    h4
    """

    sections = []

    hierarchy = {
        1: None,
        2: None,
        3: None,
        4: None,
    }

    current_section = None


    for line in text.splitlines():

        heading = parse_heading(line)

        if heading:

            level, title = heading


            # ------------------------------------------------
            # Save previous section
            # ------------------------------------------------

            if current_section:

                content = "\n".join(
                    current_section["content"]
                ).strip()

                if content:

                    current_section["content"] = (
                        content
                    )

                    sections.append(
                        current_section
                    )


            # ------------------------------------------------
            # Update hierarchy
            # ------------------------------------------------

            if level <= 4:

                hierarchy[level] = title

                # Clear lower levels
                for lower_level in range(
                    level + 1,
                    5
                ):

                    hierarchy[lower_level] = None


            current_section = {
                "level": level,
                "title": title,
                "h1": hierarchy[1],
                "h2": hierarchy[2],
                "h3": hierarchy[3],
                "h4": hierarchy[4],
                "content": [],
            }


        else:

            # ------------------------------------------------
            # Content before first heading
            # ------------------------------------------------

            if current_section is None:

                current_section = {
                    "level": 0,
                    "title": "Front Matter",
                    "h1": None,
                    "h2": None,
                    "h3": None,
                    "h4": None,
                    "content": [],
                }


            current_section["content"].append(
                line
            )


    # --------------------------------------------------------
    # Save final section
    # --------------------------------------------------------

    if current_section:

        content = "\n".join(
            current_section["content"]
        ).strip()

        if content:

            current_section["content"] = (
                content
            )

            sections.append(
                current_section
            )


    return sections


