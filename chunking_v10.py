# 10. SPLIT LARGE NORMAL TEXT
# ============================================================

def split_text_section(
    text,
    max_chars=MAX_CHARS,
    overlap_chars=OVERLAP_CHARS
):
    """
    Split only sections that exceed MAX_CHARS.

    Paragraph boundaries are preferred.
    """

    text = text.strip()

    if len(text) <= max_chars:

        return [text]


    paragraphs = re.split(
        r"\n\s*\n",
        text
    )

    chunks = []

    current_chunk = ""


    for paragraph in paragraphs:

        paragraph = paragraph.strip()

        if not paragraph:
            continue


        # ----------------------------------------------------
        # Handle a single very large paragraph
        # ----------------------------------------------------

        if len(paragraph) > max_chars:

            if current_chunk:

                chunks.append(
                    current_chunk.strip()
                )

                current_chunk = ""


            start = 0

            while start < len(paragraph):

                end = min(
                    start + max_chars,
                    len(paragraph)
                )

                piece = paragraph[
                    start:end
                ].strip()


                if piece:

                    chunks.append(
                        piece
                    )


                if end >= len(paragraph):
                    break


                start = max(
                    end - overlap_chars,
                    start + 1
                )


            continue


        # ----------------------------------------------------
        # Try adding paragraph
        # ----------------------------------------------------

        if current_chunk:

            candidate = (
                current_chunk
                + "\n\n"
                + paragraph
            )

        else:

            candidate = paragraph


        if len(candidate) <= max_chars:

            current_chunk = candidate


        else:

            if current_chunk:

                chunks.append(
                    current_chunk.strip()
                )


            # ------------------------------------------------
            # Add controlled overlap from previous chunk
            # ------------------------------------------------

            overlap = ""

            if chunks and overlap_chars > 0:

                previous = chunks[-1]

                overlap = previous[
                    -overlap_chars:
                ]

                # Start overlap near a word boundary
                space_position = (
                    overlap.find(" ")
                )

                if space_position != -1:

                    overlap = overlap[
                        space_position + 1:
                    ]


            if overlap:

                current_chunk = (
                    overlap
                    + "\n\n"
                    + paragraph
                ).strip()

            else:

                current_chunk = (
                    paragraph
                )


    if current_chunk:

        chunks.append(
            current_chunk.strip()
        )


    return chunks


