# 4. DETECT PRODUCT TYPE
# ============================================================

def detect_product_type(plan_name):
    """
    Infer product type from plan name.

    Examples:
        BEST BUY HMO - LP -> HMO
        Some PPO Plan     -> PPO
    """

    if not plan_name:
        return None

    name = plan_name.upper()

    product_patterns = [
        ("HMO", "HMO"),
        ("PPO", "PPO"),
        ("EPO", "EPO"),
        ("POS", "POS"),
        ("HSA", "HSA"),
        ("HDHP", "HDHP"),
    ]

    for keyword, product_type in product_patterns:

        if keyword in name:
            return product_type

    return None


