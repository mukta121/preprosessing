# 9. IDENTIFY TABLE SECTIONS
# ============================================================

def is_table_section(section):
    """
    Determine whether a section belongs to
    EXTRACTED TABLES / Table 1 / Table 2 etc.
    """

    values = [
        section.get("h1"),
        section.get("h2"),
        section.get("h3"),
        section.get("h4"),
        section.get("title"),
    ]


    for value in values:

        if not value:
            continue

        value_lower = value.lower()


        if "extracted tables" in value_lower:
            return True


        if re.search(
            r"\btable\s+\d+\b",
            value_lower
        ):

            return True


    return False


