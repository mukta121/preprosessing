def process_all_files():
    """
    Process every cleaned Markdown file and write
    all chunks to one JSONL file.
    """

    md_files = sorted(
        SOURCE_DIR.glob(
            "*.md"
        )
    )


    print(
        "=" * 75
    )

    print(
        "POINT32HEALTH SOB CHUNKING PIPELINE"
    )

    print(
        "=" * 75
    )


    print(
        f"\nSource directory:"
    )

    print(
        SOURCE_DIR
    )


    print(
        f"\nOutput JSONL:"
    )

    print(
        OUTPUT_JSONL
    )


    print(
        f"\nMarkdown files found: "
        f"{len(md_files)}"
    )


    if not md_files:

        print(
            "\nNo cleaned Markdown files found."
        )

        return


    total_chunks = 0

    total_text_chunks = 0

    total_table_chunks = 0

    successful_files = 0

    failed_files = 0


    # --------------------------------------------------------
    # Write all chunks into one JSONL file
    # --------------------------------------------------------

    with OUTPUT_JSONL.open(
        "w",
        encoding="utf-8"
    ) as jsonl_file:


        for file_path in md_files:

            try:

                print(
                    "\n" + "-" * 75
                )

                print(
                    f"Processing: "
                    f"{file_path.name}"
                )


                chunks = (
                    chunk_document(
                        file_path
                    )
                )


                # ------------------------------------------------
                # Write JSONL
                # ------------------------------------------------

                for chunk in chunks:

                    jsonl_file.write(
                        json.dumps(
                            chunk,
                            ensure_ascii=False
                        )
                        + "\n"
                    )


                # ------------------------------------------------
                # Statistics
                # ------------------------------------------------

                text_chunks = sum(
                    1
                    for chunk in chunks
                    if chunk["chunk_type"]
                    == "text"
                )


                table_chunks = sum(
                    1
                    for chunk in chunks
                    if chunk["chunk_type"]
                    == "table"
                )


                print(
                    f"    Total chunks : "
                    f"{len(chunks)}"
                )

                print(
                    f"    Text chunks  : "
                    f"{text_chunks}"
                )

                print(
                    f"    Table chunks : "
                    f"{table_chunks}"
                )


                # ------------------------------------------------
                # Print metadata found for document
                # ------------------------------------------------

                if chunks:

                    first_chunk = (
                        chunks[0]
                    )

                    print(
                        f"    Plan         : "
                        f"{first_chunk.get('plan_name')}"
                    )

                    print(
                        f"    State        : "
                        f"{first_chunk.get('state')}"
                    )

                    print(
                        f"    Effective    : "
                        f"{first_chunk.get('effective_date')}"
                    )

                    print(
                        f"    Form         : "
                        f"{first_chunk.get('form_number')}"
                    )

                    print(
                        f"    Product Type : "
                        f"{first_chunk.get('product_type')}"
                    )


                total_chunks += (
                    len(chunks)
                )

                total_text_chunks += (
                    text_chunks
                )

                total_table_chunks += (
                    table_chunks
                )

                successful_files += 1


            except Exception as e:

                failed_files += 1


                print(
                    f"\nERROR processing "
                    f"{file_path.name}"
                )

                print(
                    f"    Error type: "
                    f"{type(e).__name__}"
                )

                print(
                    f"    Error: {e}"
                )


    # ========================================================
    # FINAL SUMMARY
    # ========================================================

    print(
        "\n" + "=" * 75
    )

    print(
        "CHUNKING COMPLETE"
    )

    print(
        "=" * 75
    )


    print(
        f"Files successful : "
        f"{successful_files}"
    )

    print(
        f"Files failed     : "
        f"{failed_files}"
    )

    print(
        f"Total chunks     : "
        f"{total_chunks}"
    )

    print(
        f"Text chunks      : "
        f"{total_text_chunks}"
    )

    print(
        f"Table chunks     : "
        f"{total_table_chunks}"
    )


    print(
        "\nJSONL saved to:"
    )

    print(
        OUTPUT_JSONL
    )


