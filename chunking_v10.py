# 5. EXTRACT DOCUMENT METADATA
# ============================================================

def extract_document_metadata(text, file_path):
    """
    Extract useful SOB metadata.

    Metadata:
        document_id
        source_file
        plan_name
        state
        effective_date
        form_number
        product_type
    """

    metadata = {
        "document_id": get_document_id(file_path),
        "source_file": file_path.name,
        "plan_name": None,
        "state": None,
        "effective_date": None,
        "form_number": None,
        "product_type": None,
    }


    # --------------------------------------------------------
    # EFFECTIVE DATE
    #
    # Examples:
    # EFFECTIVE DATE: 01/01/2026
    # PageFooter="EFFECTIVE DATE: 01/01/2026"
    # --------------------------------------------------------

    match = re.search(
        r"EFFECTIVE\s+DATE\s*:\s*"
        r"(\d{1,2}/\d{1,2}/\d{4})",
        text,
        flags=re.IGNORECASE
    )

    if match:

        metadata["effective_date"] = (
            match.group(1).strip()
        )


    # --------------------------------------------------------
    # FORM NUMBER
    #
    # Examples:
    # FORM #1574_16
    # PageFooter="FORM #1574_16"
    # --------------------------------------------------------

    match = re.search(
        r"FORM\s*#\s*([A-Za-z0-9_\-\.]+)",
        text,
        flags=re.IGNORECASE
    )

    if match:

        metadata["form_number"] = (
            match.group(1).strip()
        )


    # --------------------------------------------------------
    # FRONT MATTER
    # --------------------------------------------------------

    first_lines = []

    for line in text.splitlines()[:80]:

        clean_line = line.strip()

        if not clean_line:
            continue

        # Ignore Markdown comments
        if clean_line.startswith("<!--"):
            continue

        # Ignore obvious document wrapper heading
        if clean_line.upper() in [
            "# DOCUMENT TEXT",
            "DOCUMENT TEXT",
            "# EXTRACTED TABLES",
        ]:
            continue

        first_lines.append(
            clean_line
        )


    # --------------------------------------------------------
    # PLAN NAME DETECTION
    #
    # Example:
    # BEST BUY HMO - LP
    # --------------------------------------------------------

    plan_keywords = [
        "HMO",
        "PPO",
        "EPO",
        "POS",
        "HSA",
        "HDHP",
    ]

    for line in first_lines:

        upper_line = line.upper()

        if any(
            keyword in upper_line
            for keyword in plan_keywords
        ):

            # Avoid accidentally selecting a whole paragraph
            if len(line) <= 150:

                metadata["plan_name"] = line

                break


    # --------------------------------------------------------
    # STATE DETECTION
    # --------------------------------------------------------

    state_mapping = {
        "MAINE": "Maine",
        "MASSACHUSETTS": "Massachusetts",
        "NEW HAMPSHIRE": "New Hampshire",
        "RHODE ISLAND": "Rhode Island",
        "CONNECTICUT": "Connecticut",
        "VERMONT": "Vermont",
    }

    for line in first_lines:

        normalized = line.upper().strip()

        if normalized in state_mapping:

            metadata["state"] = (
                state_mapping[normalized]
            )

            break


    # --------------------------------------------------------
    # PRODUCT TYPE
    # --------------------------------------------------------

    metadata["product_type"] = (
        detect_product_type(
            metadata["plan_name"]
        )
    )


    return metadata


