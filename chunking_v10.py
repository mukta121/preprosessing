# 13. CHUNK ONE DOCUMENT
# ============================================================

def chunk_document(file_path):
    """
    Chunk one cleaned SOB Markdown file.
    """

    text = file_path.read_text(
        encoding="utf-8",
        errors="ignore"
    )


    text = normalize_text(
        text
    )


    document_metadata = (
        extract_document_metadata(
            text,
            file_path
        )
    )


    sections = parse_markdown_sections(
        text
    )


    chunks = []

    chunk_index = 0


    for section in sections:

        content = section[
            "content"
        ].strip()


        # Do not create tiny standalone chunks
        if len(content) < MIN_CHUNK_CHARS:
            continue


        section_path = (
            build_section_path(
                section
            )
        )


        # ----------------------------------------------------
        # TABLE CHUNKING
        # ----------------------------------------------------

        if is_table_section(section):

            chunk_type = "table"

            section_chunks = (
                split_table_section(
                    content
                )
            )


        # ----------------------------------------------------
        # TEXT CHUNKING
        # ----------------------------------------------------

        else:

            chunk_type = "text"

            section_chunks = (
                split_text_section(
                    content
                )
            )


        # ----------------------------------------------------
        # Create individual JSON records
        # ----------------------------------------------------

        for section_chunk_index, chunk_text in enumerate(
            section_chunks,
            start=1
        ):

            chunk_text = (
                chunk_text.strip()
            )


            if len(chunk_text) < MIN_CHUNK_CHARS:
                continue


            chunk_index += 1


            chunk_id = (
                f"{document_metadata['document_id']}"
                f"_chunk_{chunk_index:04d}"
            )


            embedding_text = (
                create_embedding_text(
                    section_path,
                    chunk_text,
                    document_metadata
                )
            )


            chunk_record = {

                # ===========================================
                # IDs
                # ===========================================

                "chunk_id":
                    chunk_id,

                "document_id":
                    document_metadata[
                        "document_id"
                    ],

                "source_file":
                    document_metadata[
                        "source_file"
                    ],


                # ===========================================
                # DOCUMENT METADATA
                # ===========================================

                "plan_name":
                    document_metadata.get(
                        "plan_name"
                    ),

                "state":
                    document_metadata.get(
                        "state"
                    ),

                "effective_date":
                    document_metadata.get(
                        "effective_date"
                    ),

                "form_number":
                    document_metadata.get(
                        "form_number"
                    ),

                "product_type":
                    document_metadata.get(
                        "product_type"
                    ),


                # ===========================================
                # CHUNK INFORMATION
                # ===========================================

                "chunk_index":
                    chunk_index,

                "section_chunk_index":
                    section_chunk_index,

                "chunk_type":
                    chunk_type,


                # ===========================================
                # MARKDOWN HIERARCHY
                # ===========================================

                "h1":
                    section.get(
                        "h1"
                    ),

                "h2":
                    section.get(
                        "h2"
                    ),

                "h3":
                    section.get(
                        "h3"
                    ),

                "h4":
                    section.get(
                        "h4"
                    ),

                "section_title":
                    section.get(
                        "title"
                    ),

                "section_path":
                    section_path,


                # ===========================================
                # CONTENT
                # ===========================================

                "text":
                    chunk_text,

                "embedding_text":
                    embedding_text,


                # ===========================================
                # SIZE INFORMATION
                # ===========================================

                "char_count":
                    len(
                        chunk_text
                    ),

                "approx_token_count":
                    round(
                        len(chunk_text)
                        / 4
                    ),
            }


            chunks.append(
                chunk_record
            )


    return chunks


