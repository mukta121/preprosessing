# 11. SPLIT TABLE SECTION
# ============================================================

def split_table_section(
    text,
    max_chars=MAX_CHARS
):
    """
    Keep small Markdown tables intact.

    Large tables are split by rows while repeating
    the table header in every resulting chunk.
    """

    text = text.strip()


    if len(text) <= max_chars:

        return [text]


    lines = [
        line.strip()
        for line in text.splitlines()
        if line.strip()
    ]


    table_lines = [
        line
        for line in lines
        if "|" in line
    ]


    # --------------------------------------------------------
    # If it doesn't look like Markdown table syntax
    # --------------------------------------------------------

    if len(table_lines) < 2:

        return split_text_section(
            text,
            max_chars=max_chars,
            overlap_chars=0
        )


    # --------------------------------------------------------
    # First 2 lines:
    #
    # | Benefit | Cost |
    # | --- | --- |
    # --------------------------------------------------------

    header_lines = (
        table_lines[:2]
    )

    data_lines = (
        table_lines[2:]
    )


    header = "\n".join(
        header_lines
    )


    chunks = []

    current_rows = []


    for row in data_lines:

        candidate_rows = (
            current_rows
            + [row]
        )

        candidate = (
            header
            + "\n"
            + "\n".join(
                candidate_rows
            )
        )


        if len(candidate) <= max_chars:

            current_rows.append(
                row
            )


        else:

            if current_rows:

                chunks.append(
                    header
                    + "\n"
                    + "\n".join(
                        current_rows
                    )
                )


            current_rows = [
                row
            ]


    if current_rows:

        chunks.append(
            header
            + "\n"
            + "\n".join(
                current_rows
            )
        )


    return chunks


