# 24. SPLIT EXTRACTED TABLE AREA
# ============================================================

def split_extracted_tables(
    extracted_text: str
) -> List[Dict]:

    """
    Expected:

    ## Table 1

    | column | column |
    | --- | --- |
    ...

    ## Table 2
    ...
    """

    if not extracted_text.strip():

        return []


    table_heading_pattern = re.compile(
        r"(?im)^#{1,6}\s+"
        r"(Table\s+\d+[^\n]*)$"
    )


    matches = list(
        table_heading_pattern.finditer(
            extracted_text
        )
    )


    # No explicit Table N headings
    if not matches:

        return [{

            "table_name":
                "Extracted Table",

            "text":
                extracted_text.strip()
        }]


    tables = []


    for index, match in enumerate(
        matches
    ):

        table_name = (
            match.group(1)
            .strip()
        )


        start = match.end()


        if index + 1 < len(
            matches
        ):

            end = (
                matches[
                    index + 1
                ].start()
            )


        else:

            end = len(
                extracted_text
            )


        table_text = (
            extracted_text[
                start:end
            ]
            .strip()
        )


        if table_text:

            tables.append({

                "table_name":
                    table_name,

                "text":
                    table_text
            })


    return tables


