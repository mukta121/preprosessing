# 6. NORMALIZE TEXT
# ============================================================

def normalize_whitespace(text: str) -> str:

    """
    Normalize Markdown text while preserving tables
    and paragraph structure.
    """

    text = text.replace(
        "\r\n",
        "\n"
    )

    text = text.replace(
        "\r",
        "\n"
    )

    text = text.replace(
        "\t",
        " "
    )

    # Remove trailing spaces
    text = re.sub(
        r"[ \t]+$",
        "",
        text,
        flags=re.MULTILINE
    )

    # Reduce excessive blank lines
    text = re.sub(
        r"\n\s*\n\s*\n+",
        "\n\n",
        text
    )

    return text.strip()


# ============================================================
# 7. INTERNAL DOCUMENT ID EXTRACTION
# ============================================================

def extract_document_id(
    text: str
) -> Optional[str]:

    """
    Extract document ID from inside Markdown.

    Examples:

    ID: MD0000029007_A3

    ID: DN0000000547_A1

    <!-- PageHeader="ID: MD0000028999_A4 X" -->

    Returns:

    MD0000029007_A3
    DN0000000547_A1
    MD0000028999_A4
    """

    patterns = [

        # HTML PageHeader
        (
            r'PageHeader\s*=\s*["\']?'
            r'.*?\bID\s*:\s*'
            r'([A-Z]{2}\d+(?:_[A-Z0-9]+)?)'
        ),

        # Normal ID line
        (
            r'(?im)^\s*[\.\-]?\s*'
            r'ID\s*:\s*'
            r'([A-Z]{2}\d+(?:_[A-Z0-9]+)?)\b'
        ),

        # More permissive fallback
        (
            r'\bID\s*:\s*'
            r'([A-Z]{2}\d+(?:_[A-Z0-9]+)?)\b'
        ),
    ]


    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            flags=re.IGNORECASE
        )

        if match:

            return (
                match.group(1)
                .upper()
                .strip()
            )


    return None


