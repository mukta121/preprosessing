# 19. HTML TABLE DETECTION
# ============================================================

HTML_TABLE_PATTERN = re.compile(
    r"<table\b[^>]*>.*?</table>",
    flags=(
        re.IGNORECASE
        |
        re.DOTALL
    )
)


# ============================================================
# 20. SPLIT BODY INTO PROSE / HTML TABLE BLOCKS
# ============================================================

def split_html_aware_blocks(
    text: str
) -> List[Dict]:

    """
    HTML table is treated as an atomic block.

    It will not be arbitrarily cut through:

    <table> .... </table>
    """

    blocks = []

    cursor = 0


    for match in (
        HTML_TABLE_PATTERN.finditer(
            text
        )
    ):

        # Text before table
        before = text[
            cursor:match.start()
        ].strip()


        if before:

            blocks.append({

                "type":
                    "prose",

                "text":
                    before
            })


        # Complete HTML table
        blocks.append({

            "type":
                "html_table",

            "text":
                match.group(0)
                .strip()
        })


        cursor = match.end()


    # Remaining content
    after = text[
        cursor:
    ].strip()


    if after:

        blocks.append({

            "type":
                "prose",

            "text":
                after
        })


    return blocks


