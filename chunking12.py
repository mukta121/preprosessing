# 25. MARKDOWN TABLE CHUNKER
# ============================================================

def chunk_markdown_table(
    table_text: str,
    table_name: str,
    max_chars: int = TABLE_CHUNK_SIZE
) -> List[str]:

    """
    Markdown table strategy:

    - preserve complete rows
    - repeat table header
    - no character overlap
    """

    lines = [

        line.strip()

        for line in table_text.splitlines()

        if line.strip()
    ]


    table_lines = [

        line

        for line in lines

        if "|" in line
    ]


    # Not recognizable as Markdown table
    if len(table_lines) < 2:

        return [
            table_text.strip()
        ]


    # Normally:
    # Row 1 = column header
    # Row 2 = markdown separator
    header_lines = (
        table_lines[:2]
    )


    data_rows = (
        table_lines[2:]
    )


    header = "\n".join(
        header_lines
    )


    prefix = (
        f"Table: {table_name}"
        + "\n\n"
        + header
    )


    chunks = []

    current_rows = []


    for row in data_rows:

        candidate_rows = (
            current_rows
            + [row]
        )


        candidate = (
            prefix
            + "\n"
            + "\n".join(
                candidate_rows
            )
        )


        if len(candidate) <= max_chars:

            current_rows.append(
                row
            )


        else:

            # Save current rows
            if current_rows:

                chunks.append(
                    (
                        prefix
                        + "\n"
                        + "\n".join(
                            current_rows
                        )
                    ).strip()
                )


            # Start new table chunk
            current_rows = [
                row
            ]


    if current_rows:

        chunks.append(
            (
                prefix
                + "\n"
                + "\n".join(
                    current_rows
                )
            ).strip()
        )


    # Table has only headings
    if not chunks:

        chunks.append(
            prefix.strip()
        )


    return chunks


