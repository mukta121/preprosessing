# 16. SPLIT BODY FROM EXTRACTED TABLES
# ============================================================

def split_document_parts(
    text: str
) -> Dict[str, str]:

    """
    Split into:

    document_body
    extracted_tables

    using heading:

    # EXTRACTED TABLES
    """

    pattern = re.compile(
        r"(?im)^#{1,6}\s+"
        r"EXTRACTED\s+TABLES\s*$"
    )


    match = pattern.search(
        text
    )


    if not match:

        return {

            "document_body":
                text.strip(),

            "extracted_tables":
                ""
        }


    return {

        "document_body":
            text[
                :match.start()
            ].strip(),

        "extracted_tables":
            text[
                match.end():
            ].strip()
    }


# ============================================================
# 17. HIERARCHICAL MARKDOWN SECTION PARSER
# ============================================================

def split_into_sections(
    text: str
) -> List[Dict]:

    """
    Split document body by Markdown headings and
    preserve H1-H4 hierarchy.
    """

    lines = text.splitlines()

    sections = []

    hierarchy = {
        1: None,
        2: None,
        3: None,
        4: None,
    }


    current = None


    heading_pattern = re.compile(
        r"^(#{1,6})\s+(.+?)\s*$"
    )


    for line in lines:

        heading = heading_pattern.match(
            line
        )


        if heading:

            level = len(
                heading.group(1)
            )

            title = (
                heading.group(2)
                .strip()
            )


            # Save previous section
            if current:

                section_text = (
                    "\n".join(
                        current["content"]
                    )
                    .strip()
                )


                if section_text:

                    current[
                        "text"
                    ] = section_text

                    del current[
                        "content"
                    ]

                    sections.append(
                        current
                    )


            # Update hierarchy
            if level <= 4:

                hierarchy[
                    level
                ] = title


                # Reset children
                for lower_level in range(
                    level + 1,
                    5
                ):

                    hierarchy[
                        lower_level
                    ] = None


            current = {

                "section":
                    title,

                "level":
                    level,

                "h1":
                    hierarchy[1],

                "h2":
                    hierarchy[2],

                "h3":
                    hierarchy[3],

                "h4":
                    hierarchy[4],

                # Keep heading in chunk text
                "content": [
                    line
                ]
            }


        else:

            if current is None:

                current = {

                    "section":
                        "Document Header",

                    "level":
                        0,

                    "h1":
                        None,

                    "h2":
                        None,

                    "h3":
                        None,

                    "h4":
                        None,

                    "content": []
                }


            current[
                "content"
            ].append(
                line
            )


    # Save final section
    if current:

        section_text = (
            "\n".join(
                current["content"]
            )
            .strip()
        )


        if section_text:

            current[
                "text"
            ] = section_text

            del current[
                "content"
            ]

            sections.append(
                current
            )


    return sections


# ============================================================
# 18. BUILD SECTION PATH
# ============================================================

def build_section_path(
    section: Dict
) -> str:

    parts = []


    for key in [
        "h1",
        "h2",
        "h3",
        "h4",
    ]:

        value = section.get(
            key
        )


        if (
            value
            and
            value not in parts
        ):

            parts.append(
                value
            )


    if not parts:

        section_name = section.get(
            "section"
        )


        if section_name:

            parts.append(
                section_name
            )


    return " > ".join(
        parts
    )


