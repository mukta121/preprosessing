# ============================================================
# 11. REMOVE MARKDOWN MARKUP FROM A LINE
# ============================================================

def remove_markdown_markup(
    line: str
) -> str:

    line = line.strip()

    line = re.sub(
        r"^#{1,6}\s*",
        "",
        line
    )

    line = re.sub(
        r"<!--.*?-->",
        "",
        line
    )

    return line.strip()


# ============================================================
# 12. CLEAN PLAN NAME
# ============================================================

def clean_plan_name(
    plan_name: str
) -> Optional[str]:

    if not plan_name:
        return None


    plan_name = normalize_whitespace(
        plan_name.replace(
            "\n",
            " "
        )
    )


    # Remove trailing state name
    for state in STATE_PATTERNS:

        plan_name = re.sub(
            rf"\b{re.escape(state)}\b\s*$",
            "",
            plan_name,
            flags=re.IGNORECASE
        ).strip()


    return (
        plan_name
        if plan_name
        else None
    )


# ============================================================
# 13. PLAN NAME EXTRACTION
# ============================================================

def extract_plan_name(
    text: str
) -> Optional[str]:

    """
    Extract plan name primarily from opening SOB heading area.
    """

    lines = [

        remove_markdown_markup(
            line
        )

        for line in text.splitlines()
    ]


    lines = [

        line

        for line in lines

        if line
    ]


    useful = []


    for line in lines[:50]:

        upper = line.upper()


        # Skip wrappers
        if upper in {
            "DOCUMENT TEXT",
            "EXTRACTED TABLES",
        }:

            continue


        # Skip ID metadata
        if re.search(
            r"^\s*\.?\s*ID\s*:",
            upper
        ):

            continue


        # Skip dates
        if upper.startswith(
            "DATE:"
        ):

            continue


        if upper.startswith(
            "EFFECTIVE DATE:"
        ):

            continue


        if upper.startswith(
            "FORM "
        ):

            continue


        # Skip page metadata
        if "PAGEHEADER=" in upper:

            continue


        if "PAGEFOOTER=" in upper:

            continue


        if upper == "X":

            continue


        useful.append(
            line
        )


    if not useful:

        return None


    # ========================================================
    # SCHEDULE OF BENEFITS
    # ========================================================

    for index, line in enumerate(
        useful
    ):

        if (
            "SCHEDULE OF BENEFITS"
            not in line.upper()
        ):

            continue


        after = re.sub(
            r"(?i)^.*?"
            r"SCHEDULE\s+OF\s+BENEFITS\s*",
            "",
            line
        ).strip()


        candidates = []


        if after:

            candidates.append(
                after
            )


        for next_line in useful[
            index + 1:index + 7
        ]:

            upper = (
                next_line.upper()
            )


            # Stop at narrative
            stop_phrases = [

                "PLEASE NOTE",

                "IMPORTANT INFORMATION",

                "THIS SCHEDULE",

                "THIS PLAN",

                "SERVICES ARE",

                "COVERAGE UNDER",

                "THE FOLLOWING",

                "YOUR BENEFITS",

                "BENEFITS ARE",
            ]


            if any(
                upper.startswith(
                    phrase
                )
                for phrase
                in stop_phrases
            ):

                break


            candidates.append(
                next_line
            )


        candidate = (
            " ".join(
                candidates
            )
            .strip()
        )


        if candidate:

            return clean_plan_name(
                candidate
            )


    # ========================================================
    # SPECIAL DOCUMENT TYPES
    # ========================================================

    special_pattern = re.compile(
        r"(?i)\b("
        r"PEDIATRIC\s+DENTAL|"
        r"DENTAL\s+RIDER|"
        r"VISIONCARE|"
        r"MEDICARE\s+ENHANCE|"
        r"SENIOR\s+CARE\s+OPTIONS|"
        r"USFHP"
        r")\b"
    )


    for index, line in enumerate(
        useful[:15]
    ):

        if special_pattern.search(
            line
        ):

            candidate = (
                " ".join(
                    useful[
                        index:index + 4
                    ]
                )
            )

            return clean_plan_name(
                candidate
            )


    # Final fallback
    return clean_plan_name(
        useful[0]
    )


