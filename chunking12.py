# 21. CLEAN OVERLAP
# ============================================================

def get_overlap_text(
    previous_text: str,
    overlap: int
) -> str:

    """
    Return clean overlap without intentionally
    starting in the middle of a paragraph.
    """

    if (
        not previous_text
        or overlap <= 0
    ):

        return ""


    tail = previous_text[
        -overlap:
    ]


    # Prefer paragraph
    position = tail.find(
        "\n\n"
    )


    if position != -1:

        return tail[
            position + 2:
        ].strip()


    # Then line boundary
    position = tail.find(
        "\n"
    )


    if position != -1:

        return tail[
            position + 1:
        ].strip()


    # Then sentence
    position = tail.find(
        ". "
    )


    if position != -1:

        return tail[
            position + 2:
        ].strip()


    return tail.strip()


# ============================================================
# 22. SPLIT LARGE PROSE
# ============================================================

def split_large_prose(
    text: str,
    chunk_size: int = CHUNK_SIZE,
    overlap: int = CHUNK_OVERLAP,
    min_chunk: int = MIN_CHUNK
) -> List[str]:

    """
    Paragraph-aware prose splitting.
    """

    text = text.strip()


    if not text:

        return []


    # Preserve complete short section
    if len(text) <= chunk_size:

        return [
            text
        ]


    paragraphs = re.split(
        r"\n\s*\n",
        text
    )


    chunks = []

    current = ""


    for paragraph in paragraphs:

        paragraph = (
            paragraph.strip()
        )


        if not paragraph:

            continue


        candidate = (
            current
            + "\n\n"
            + paragraph
        ).strip()


        # Fits
        if len(candidate) <= chunk_size:

            current = candidate

            continue


        # Save previous
        if current:

            chunks.append(
                current.strip()
            )


        # ====================================================
        # A single paragraph is too large
        # ====================================================

        if len(paragraph) > chunk_size:

            start = 0


            while start < len(
                paragraph
            ):

                end = min(
                    start + chunk_size,
                    len(paragraph)
                )


                # Try sentence boundary
                if end < len(
                    paragraph
                ):

                    search_start = max(
                        start,
                        end - 800
                    )


                    sentence_end = max(

                        paragraph.rfind(
                            ". ",
                            search_start,
                            end
                        ),

                        paragraph.rfind(
                            ".\n",
                            search_start,
                            end
                        )
                    )


                    if (
                        sentence_end
                        > start
                    ):

                        end = (
                            sentence_end
                            + 1
                        )


                piece = (
                    paragraph[
                        start:end
                    ]
                    .strip()
                )


                if len(piece) >= min_chunk:

                    chunks.append(
                        piece
                    )


                elif piece and chunks:

                    # Merge small residual
                    chunks[-1] = (
                        chunks[-1]
                        + " "
                        + piece
                    )


                if end >= len(
                    paragraph
                ):

                    break


                start = max(
                    end - overlap,
                    start + 1
                )


            current = ""


        else:

            overlap_text = ""


            if chunks:

                overlap_text = (
                    get_overlap_text(
                        chunks[-1],
                        overlap
                    )
                )


            current = (
                overlap_text
                + "\n\n"
                + paragraph
            ).strip()


    # Final chunk
    if current:

        current = current.strip()


        if len(current) >= min_chunk:

            chunks.append(
                current
            )


        elif chunks:

            chunks[-1] = (
                chunks[-1]
                + "\n\n"
                + current
            ).strip()


        else:

            chunks.append(
                current
            )


    return chunks


