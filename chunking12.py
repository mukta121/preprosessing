# 14. PRODUCT TYPE EXTRACTION
# ============================================================

def extract_product_type(
    text: str,
    plan_name: Optional[str] = None
) -> str:

    """
    Infer normalized product type.

    Examples:

    BEST BUY HMO 4000 FLEX
        -> HMO

    NATIONAL ACCESS EPO HSA
        -> EPO

    BEST BUY HSA PPO
        -> PPO

    EXPLORER POS
        -> POS
    """

    # Strong preference for opening document information.
    searchable = (
        (plan_name or "")
        + "\n"
        + text[:6000]
    ).upper()


    for (
        product_type,
        patterns
    ) in PRODUCT_PATTERNS:

        for pattern in patterns:

            if re.search(
                pattern,
                searchable,
                flags=re.IGNORECASE
            ):

                return product_type


    return "UNKNOWN"


