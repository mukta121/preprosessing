# 15. PLAN VARIANT EXTRACTION
# ============================================================

def extract_plan_variants(
    text: str,
    plan_name: Optional[str]
) -> List[str]:

    searchable = (
        (plan_name or "")
        + "\n"
        + text[:4000]
    ).upper()


    found = []


    for (
        variant,
        patterns
    ) in PLAN_VARIANT_PATTERNS.items():

        for pattern in patterns:

            if re.search(
                pattern,
                searchable,
                flags=re.IGNORECASE
            ):

                if variant not in found:

                    found.append(
                        variant
                    )

                break


    # Flex Plus is more specific than Flex
    if (
        "Flex Plus" in found
        and
        "Flex" in found
    ):

        found.remove(
            "Flex"
        )


    return found


