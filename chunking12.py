# 26. BUILD EMBEDDING TEXT
# ============================================================

def build_embedding_text(
    chunk_text_value: str,
    metadata: Dict
) -> str:

    """
    Add semantic metadata before content.

    Structured metadata remains separately available
    for Azure AI Search filtering.
    """

    parts = []


    if metadata.get(
        "plan_name"
    ):

        parts.append(
            f"Plan: "
            f"{metadata['plan_name']}"
        )


    if (
        metadata.get(
            "product_type"
        )
        and
        metadata[
            "product_type"
        ] != "UNKNOWN"
    ):

        parts.append(
            f"Product Type: "
            f"{metadata['product_type']}"
        )


    if metadata.get(
        "plan_variant"
    ):

        parts.append(
            f"Plan Variant: "
            f"{metadata['plan_variant']}"
        )


    if metadata.get(
        "state"
    ):

        parts.append(
            f"State: "
            f"{metadata['state']}"
        )


    if metadata.get(
        "section_path"
    ):

        parts.append(
            f"Section: "
            f"{metadata['section_path']}"
        )


    if metadata.get(
        "table_name"
    ):

        parts.append(
            f"Table: "
            f"{metadata['table_name']}"
        )


    header = "\n".join(
        parts
    )


    if header:

        return (
            header
            + "\n\n"
            + chunk_text_value
        )


    return chunk_text_value


