# 8. EFFECTIVE DATE EXTRACTION
# ============================================================

def extract_effective_date(
    text: str
) -> Optional[str]:

    """
    Examples:

    DATE: 01/01/2020

    EFFECTIVE DATE: 01/01/2026
    """

    patterns = [

        (
            r'(?im)^\s*'
            r'EFFECTIVE\s+DATE\s*:\s*'
            r'(\d{1,2}/\d{1,2}/\d{4})'
        ),

        (
            r'(?im)^\s*'
            r'DATE\s*:\s*'
            r'(\d{1,2}/\d{1,2}/\d{4})'
        ),

        (
            r'\bEFFECTIVE\s+DATE\s*:\s*'
            r'(\d{1,2}/\d{1,2}/\d{4})'
        ),
    ]


    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            flags=re.IGNORECASE
        )

        if match:

            return match.group(1)


    return None


