                # Write JSONL
                # --------------------------------------------

                for record in records:

                    writer.write(

                        json.dumps(
                            record,
                            ensure_ascii=False
                        )

                        + "\n"
                    )


                total_documents += 1

                total_chunks += len(
                    records
                )


                text_chunks = sum(

                    1

                    for record in records

                    if (
                        record[
                            "chunk_type"
                        ]
                        ==
                        "text"
                    )
                )


                table_chunks = sum(

                    1

                    for record in records

                    if (
                        record[
                            "chunk_type"
                        ]
                        ==
                        "table"
                    )
                )


                total_text_chunks += (
                    text_chunks
                )

                total_table_chunks += (
                    table_chunks
                )


                # --------------------------------------------
                # Distribution
                # --------------------------------------------

                product = (
                    records[0][
                        "product_type"
                    ]
                )


