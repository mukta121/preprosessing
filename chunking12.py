# 23. DOCUMENT BODY CHUNKER
# ============================================================

def chunk_document_section(
    section_text: str,
    chunk_size: int = CHUNK_SIZE
) -> List[str]:

    """
    Body chunking:

    - prose handled normally
    - HTML tables preserved
    - HTML tables treated atomically
    - surrounding section context retained when possible
    """

    blocks = split_html_aware_blocks(
        section_text
    )


    if not blocks:

        return []


    chunks = []

    current = ""


    for block in blocks:

        block_type = block[
            "type"
        ]

        block_text = block[
            "text"
        ].strip()


        if not block_text:

            continue


        # ====================================================
        # HTML TABLE
        # ====================================================

        if block_type == "html_table":

            candidate = (
                current
                + "\n\n"
                + block_text
            ).strip()


            # Fits with current context
            if len(candidate) <= chunk_size:

                current = candidate

                continue


            # Save preceding prose
            if current:

                chunks.append(
                    current.strip()
                )

                current = ""


            # IMPORTANT:
            # Preserve HTML table even if larger than target.
            if len(block_text) > chunk_size:

                chunks.append(
                    block_text
                )


            else:

                current = (
                    block_text
                )


        # ====================================================
        # NORMAL PROSE
        # ====================================================

        else:

            if len(block_text) > chunk_size:

                if current:

                    chunks.append(
                        current.strip()
                    )

                    current = ""


                chunks.extend(
                    split_large_prose(
                        block_text
                    )
                )

                continue


            candidate = (
                current
                + "\n\n"
                + block_text
            ).strip()


            if len(candidate) <= chunk_size:

                current = candidate


            else:

                if current:

                    chunks.append(
                        current.strip()
                    )


                overlap_text = ""


                if chunks:

                    # Do not deliberately overlap HTML markup
                    previous = chunks[
                        -1
                    ]


                    if not (
                        "<table" in
                        previous.lower()
                    ):

                        overlap_text = (
                            get_overlap_text(
                                previous,
                                CHUNK_OVERLAP
                            )
                        )


                current = (
                    overlap_text
                    + "\n\n"
                    + block_text
                ).strip()


    if current:

        chunks.append(
            current.strip()
        )


    return [
        chunk

        for chunk in chunks

        if chunk.strip()
    ]


