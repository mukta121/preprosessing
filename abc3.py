# 3. REMOVE REPEATED HEADERS
# ============================================================

def remove_repeated_headers(text):
    """
    Remove known repeated document-specific Markdown headings.

    These should only contain headings that are known to be
    repeated page/header artifacts and not meaningful content.
    """

    repeated_header_patterns = [
        r"(?im)^#+\s*PEDIATRIC DENTAL RIDER.*$",
        r"(?im)^#+\s*BEST BUY HMO.*$",
        r"(?im)^#+\s*VISIONCARE.*$",
    ]

    for pattern in repeated_header_patterns:

        text = re.sub(
            pattern,
            "",
            text
        )

    return text


# ============================================================
# 4. REMOVE PAGE / COMPANY ARTIFACTS
# ============================================================

def remove_page_artifacts(text):
    """
    Remove repeated standalone company-name artifacts.

    This does NOT remove company names when they appear
    naturally inside meaningful paragraphs.
    """

    patterns = [
        r"(?im)^\s*Harvard Pilgrim Health Care\s*$",
        r"(?im)^\s*Harvard Pilgrim Health Care,\s*Inc\.\s*$",
        r"(?im)^\s*Harvard Pilgrim Health Care of New England,\s*Inc\.\s*$",
    ]

    for pattern in patterns:

        text = re.sub(
            pattern,
            "",
            text
        )

    return text


