# 2. REMOVE LARGE NOISE SECTIONS
# ============================================================

def remove_large_noise_sections(text):
    """
    Remove complete unwanted boilerplate sections.

    Important:
    - Removes the target heading.
    - Removes all nested subheadings and content below it.
    - Stops only when another heading of the same or higher
      Markdown level is found.

    Example:

    ### General List of Exclusions MASSACHUSETTS
    #### Exclusion
    ##### Alternative Treatments
    ##### Dental Services

    All of the above will be removed as one section.
    """

    # Normalize line endings
    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")

    # Partial heading patterns.
    # .* allows suffixes such as:
    #
    # General Notice About Nondiscrimination and Accessibility Requirements
    # General List of Exclusions MASSACHUSETTS
    #
    target_patterns = [
        r"Language Assistance Services.*",
        r"General Notice About Nondiscrimination.*",
        r"General List of Exclusions.*",
    ]

    for target in target_patterns:

        removed_count = 0

        # Find target Markdown heading
        heading_pattern = re.compile(
            rf"(?im)^(?P<hashes>#+)[ \t]*{target}[ \t]*$"
        )

        while True:

            match = heading_pattern.search(text)

            if not match:
                break

            heading_level = len(
                match.group("hashes")
            )

            section_start = match.start()

            # ------------------------------------------------
            # Find next heading of SAME or HIGHER importance
            #
            # If target heading is:
            #
            # ### General List of Exclusions
            #
            # then:
            #
            # #### Exclusion
            # ##### Dental Services
            #
            # belong inside this section.
            #
            # We stop only at:
            #
            # #
            # ##
            # ###
            # ------------------------------------------------

            remaining_text = text[
                match.end():
            ]

            next_heading_pattern = re.compile(
                rf"(?m)^#{{1,{heading_level}}}[ \t]+\S"
            )

            next_match = next_heading_pattern.search(
                remaining_text
            )

            if next_match:

                section_end = (
                    match.end()
                    + next_match.start()
                )

            else:

                # Section continues to end of document
                section_end = len(text)

            # Remove section
            text = (
                text[:section_start]
                + text[section_end:]
            )

            removed_count += 1

        print(
            f"    {target}: removed "
            f"{removed_count} occurrence(s)"
        )

    return text


