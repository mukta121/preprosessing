# 7. REMOVE CONSECUTIVE DUPLICATE PROSE LINES
# ============================================================

def remove_duplicate_lines(text):
    """
    Remove immediately repeated duplicate prose lines.

    Important:
    - HTML table content is preserved.
    - Markdown table content is preserved.
    - Duplicate removal is only applied to ordinary text.
    """

    lines = text.splitlines()

    deduped = []

    inside_html_table = False

    for line in lines:

        stripped = line.strip()

        # ----------------------------------------------------
        # HTML TABLE START
        # ----------------------------------------------------

        if re.search(
            r"<table\b",
            stripped,
            flags=re.IGNORECASE
        ):
            inside_html_table = True

        # ----------------------------------------------------
        # PRESERVE HTML TABLES
        # ----------------------------------------------------

        if inside_html_table:

            deduped.append(line)

            if re.search(
                r"</table>",
                stripped,
                flags=re.IGNORECASE
            ):
                inside_html_table = False

            continue

        # ----------------------------------------------------
        # PRESERVE MARKDOWN TABLE ROWS
        # ----------------------------------------------------

        if stripped.startswith("|"):

            deduped.append(line)

            continue

        # ----------------------------------------------------
        # FIRST LINE
        # ----------------------------------------------------

        if not deduped:

            deduped.append(line)

            continue

        previous_line = deduped[-1].strip()

        # ----------------------------------------------------
        # REMOVE ONLY IMMEDIATE EXACT DUPLICATES
        # ----------------------------------------------------

        if stripped != previous_line:

            deduped.append(line)

    return "\n".join(deduped)


