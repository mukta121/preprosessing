def process_files():
    """
    Process all Markdown files inside SOURCE_DIR.
    """

    md_files = sorted(
        SOURCE_DIR.glob("*.md")
    )

    print(
        "=" * 70
    )

    print(
        "MARKDOWN PREPROCESSING FOR RAG"
    )

    print(
        "=" * 70
    )

    print(
        f"\nSource directory:\n{SOURCE_DIR}"
    )

    print(
        f"\nDestination directory:\n{DEST_DIR}"
    )

    print(
        f"\nFound {len(md_files)} Markdown files."
    )

    # --------------------------------------------------------
    # NO FILES FOUND
    # --------------------------------------------------------

    if len(md_files) == 0:

        print(
            "\nNo Markdown files found."
        )

        return

    successful = 0
    failed = 0

    # --------------------------------------------------------
    # PROCESS EACH FILE
    # --------------------------------------------------------

    for file_path in md_files:

        try:

            process_single_file(
                file_path
            )

            successful += 1

        except Exception as e:

            failed += 1

            print(
                f"\nERROR processing: "
                f"{file_path.name}"
            )

            print(
                f"    Error type: "
                f"{type(e).__name__}"
            )

            print(
                f"    Error: {e}"
            )

    # ========================================================
    # FINAL SUMMARY
    # ========================================================

    print(
        "\n" + "=" * 70
    )

    print(
        "PROCESS COMPLETED"
    )

    print(
        "=" * 70
    )

    print(
        f"Total files : {len(md_files)}"
    )

    print(
        f"Successful  : {successful}"
    )

    print(
        f"Failed      : {failed}"
    )

    print(
        f"\nCleaned files saved to:\n{DEST_DIR}"
    )


