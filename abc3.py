# 8. CLEAN WHITESPACE
# ============================================================

def clean_whitespace(text):
    """
    Remove unnecessary whitespace while retaining useful
    Markdown structure.
    """

    # Remove trailing spaces
    text = re.sub(
        r"[ \t]+$",
        "",
        text,
        flags=re.MULTILINE
    )

    # Replace 3+ blank areas with max 2 newlines
    text = re.sub(
        r"\n\s*\n\s*\n+",
        "\n\n",
        text
    )

    return text.strip()


# ============================================================
# 9. MAIN MARKDOWN CLEANING FUNCTION
# ============================================================

def clean_markdown(text):
    """
    Perform generic Markdown cleaning for RAG preprocessing.

    Important content retained:
    - Markdown headings
    - HTML tables
    - Markdown tables
    - EXTRACTED TABLES section
    - meaningful document text
    """

    # Normalize line endings
    text = text.replace(
        "\r\n",
        "\n"
    )

    text = text.replace(
        "\r",
        "\n"
    )

    # Remove page extraction metadata
    text = remove_page_metadata_comments(
        text
    )

    # Remove company/page artifacts
    text = remove_page_artifacts(
        text
    )

    # Remove known repeated document headers
    text = remove_repeated_headers(
        text
    )

    # Remove Markdown URLs but retain label text
    text = remove_markdown_links(
        text
    )

    # Remove only safe duplicate prose lines
    text = remove_duplicate_lines(
        text
    )

    # Clean excessive whitespace
    text = clean_whitespace(
        text
    )

    return text


