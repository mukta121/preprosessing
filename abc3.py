# 11. PROCESS SINGLE FILE
# ============================================================

def process_single_file(file_path):
    """
    Process and save one Markdown file.
    """

    print(
        "\n" + "=" * 70
    )

    print(
        f"Processing: {file_path.name}"
    )

    # --------------------------------------------------------
    # READ ORIGINAL FILE
    # --------------------------------------------------------

    text = file_path.read_text(
        encoding="utf-8",
        errors="ignore"
    )

    original_length = len(text)

    # --------------------------------------------------------
    # REMOVE COMPLETE LARGE UNWANTED SECTIONS
    # --------------------------------------------------------

    text = remove_large_noise_sections(
        text
    )

    # --------------------------------------------------------
    # GENERAL MARKDOWN CLEANING
    # --------------------------------------------------------

    cleaned_text = clean_markdown(
        text
    )

    # --------------------------------------------------------
    # VALIDATE
    # --------------------------------------------------------

    remaining_sections = validate_cleaning(
        cleaned_text
    )

    # --------------------------------------------------------
    # OUTPUT PATH
    # --------------------------------------------------------

    output_file = (
        DEST_DIR
        / file_path.name
    )

    # --------------------------------------------------------
    # SAVE FILE
    # --------------------------------------------------------

    output_file.write_text(
        cleaned_text,
        encoding="utf-8"
    )

    cleaned_length = len(
        cleaned_text
    )

    removed_length = (
        original_length
        - cleaned_length
    )

    # --------------------------------------------------------
    # LOGGING
    # --------------------------------------------------------

    print(
        f"    Original characters : "
        f"{original_length:,}"
    )

    print(
        f"    Cleaned characters  : "
        f"{cleaned_length:,}"
    )

    print(
        f"    Removed characters  : "
        f"{removed_length:,}"
    )

    if remaining_sections:

        print(
            "    WARNING: unwanted sections "
            "still remain:"
        )

        for section in remaining_sections:

            print(
                f"      - {section}"
            )

    else:

        print(
            "    Validation OK"
        )

    print(
        f"    Saved to: {output_file}"
    )


