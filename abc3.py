# 5. REMOVE PAGE METADATA COMMENTS
# ============================================================

def remove_page_metadata_comments(text):
    """
    Remove page extraction metadata such as:

    <!-- PageFooter="..." -->
    <!-- PageNumber="15" -->
    <!-- PageBreak -->

    These are extraction artifacts and usually not useful
    for semantic retrieval.
    """

    patterns = [

        # Page footer
        r'(?is)<!--\s*PageFooter\s*=.*?-->',

        # Page number
        r'(?is)<!--\s*PageNumber\s*=.*?-->',

        # Page break
        r'(?is)<!--\s*PageBreak\s*-->',

    ]

    for pattern in patterns:

        text = re.sub(
            pattern,
            "",
            text
        )

    return text


# ============================================================
# 6. REMOVE MARKDOWN LINKS BUT KEEP LABEL TEXT
# ============================================================

def remove_markdown_links(text):
    """
    Convert:

    [Member Portal](https://example.com)

    into:

    Member Portal
    """

    text = re.sub(
        r"\[([^\]]+)\]\((.*?)\)",
        r"\1",
        text
    )

    return text


