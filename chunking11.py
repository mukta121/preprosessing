# 14. CHUNKING
# ============================================================
def chunk_text(
    text: str,
    chunk_size: int = CHUNK_SIZE,
    overlap: int = CHUNK_OVERLAP,
    min_chunk: int = MIN_CHUNK
) -> List[str]:
    """
    Character-based paragraph-aware chunking.

    - Target max chunk size = CHUNK_SIZE
    - Overlap between large chunks = CHUNK_OVERLAP
    - Ignore tiny chunks below MIN_CHUNK
    """

    text = text.strip()

    # Empty text
    if not text:
        return []

    # --------------------------------------------------------
    # Small section:
    # keep only if it is large enough
    # --------------------------------------------------------

    if len(text) <= chunk_size:

        if len(text) >= min_chunk:
            return [text]

        return []


    paragraphs = re.split(
        r"\n\s*\n",
        text
    )


    chunks = []

    current = ""


    for paragraph in paragraphs:

        paragraph = paragraph.strip()

        if not paragraph:
            continue


        candidate = (
            current
            + "\n\n"
            + paragraph
        ).strip()


        # ----------------------------------------------------
        # Paragraph fits inside current chunk
        # ----------------------------------------------------

        if len(candidate) <= chunk_size:

            current = candidate

            continue


        # ----------------------------------------------------
        # Save current chunk before starting new one
        # ----------------------------------------------------

        if current:

            if len(current.strip()) >= min_chunk:

                chunks.append(
                    current.strip()
                )


        # ----------------------------------------------------
        # Paragraph itself is larger than chunk size
        # ----------------------------------------------------

        if len(paragraph) > chunk_size:

            start = 0


            while start < len(paragraph):

                end = min(
                    start + chunk_size,
                    len(paragraph)
                )


                piece = paragraph[
                    start:end
                ].strip()


                if len(piece) >= min_chunk:

                    chunks.append(
                        piece
                    )


                if end >= len(paragraph):
                    break


                start = max(
                    end - overlap,
                    start + 1
                )


            current = ""


        # ----------------------------------------------------
        # Normal paragraph starts a new chunk
        # ----------------------------------------------------

        else:

            previous_tail = ""


            if chunks and overlap > 0:

                previous_tail = (
                    chunks[-1][
                        -overlap:
                    ]
                )


            current = (
                previous_tail
                + "\n\n"
                + paragraph
            ).strip()


    # --------------------------------------------------------
    # Final remaining chunk
    # --------------------------------------------------------

    if current:

        if len(current.strip()) >= min_chunk:

            chunks.append(
                current.strip()
            )


    return chunks

# ============================================================
# 15. EMBEDDING TEXT
# ============================================================

def build_embedding_text(
    chunk_text_value: str,
    metadata: Dict
) -> str:
    """
    Include useful semantic metadata in the embedding input.

    IDs/form numbers are deliberately NOT emphasized because
    they provide little semantic value.

    plan_name/state/product_type are useful because users may ask:
        "What does the Best Buy HMO cover?"
        "What are Maine HMO emergency benefits?"
        "What is the National Access EPO deductible?"
    """

    parts = []

    if metadata.get("plan_name"):
        parts.append(
            f"Plan: {metadata['plan_name']}"
        )

    if metadata.get("product_type") and \
       metadata["product_type"] != "UNKNOWN":

        parts.append(
            f"Product type: {metadata['product_type']}"
        )

    if metadata.get("plan_variant"):

        parts.append(
            f"Plan variant: {metadata['plan_variant']}"
        )

    if metadata.get("state"):

        parts.append(
            f"State: {metadata['state']}"
        )

    if metadata.get("section"):

        parts.append(
            f"Section: {metadata['section']}"
        )

    metadata_header = "\n".join(parts)

    if metadata_header:

        return (
            metadata_header +
            "\n\n" +
            chunk_text_value
        )

    return chunk_text_value


