# 6. DOCUMENT ID EXTRACTION
# ============================================================

def extract_document_id(text: str) -> Optional[str]:
    """
    Extract ID from the markdown itself.

    Supported examples:

    <!-- PageHeader="ID: MD0000028999_A4 X" -->

    ID: MD0000029007_A3
    X

    ID: DN0000000547_A1
    DATE: 01/01/2020

    <!-- PageHeader="ID: MD00000201951" -->

    Extra trailing standalone X is removed automatically.
    """

    patterns = [

        # HTML PageHeader
        r'PageHeader\s*=\s*["\']?\s*ID\s*:\s*([A-Z]{2}\d+(?:_[A-Z0-9]+)?)',

        # Normal ID line
        r'(?im)^\s*[\.\-]?\s*ID\s*:\s*([A-Z]{2}\d+(?:_[A-Z0-9]+)?)\b',

        # More permissive fallback
        r'\bID\s*:\s*([A-Z]{2}\d+(?:_[A-Z0-9]+)?)\b',
    ]

    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE)

        if match:
            return match.group(1).upper().strip()

    return None


