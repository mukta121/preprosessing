def extract_form_number(text: str) -> Optional[str]:
    """
    Extract form numbers only where there is a clear label.

    We intentionally do NOT assume document_id == form_number.
    """

    patterns = [

        r'(?im)^\s*FORM\s*(?:NUMBER|NO\.?|#)?\s*[:\-]\s*([A-Z0-9._\-/]+)',

        r'(?im)^\s*FORM\s+([A-Z0-9._\-/]{4,})\s*$',
    ]

    for pattern in patterns:

        match = re.search(pattern, text)

        if match:
            return match.group(1).strip()

    return None


