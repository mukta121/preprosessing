# 16. PROCESS ONE MARKDOWN DOCUMENT
# ============================================================

def process_markdown_file(
    file_path: Path
) -> List[Dict]:

    text = file_path.read_text(
        encoding="utf-8",
        errors="ignore"
    )

    text = normalize_whitespace(text)

    # --------------------------------------------------------
    # Document-level metadata
    # --------------------------------------------------------

    document_id = extract_document_id(text)

    plan_name = extract_plan_name(text)

    state = extract_state(text)

    effective_date = extract_effective_date(text)

    form_number = extract_form_number(text)

    product_type = extract_product_type(
        text=text,
        plan_name=plan_name
    )

    variants = extract_plan_variants(
        text=text,
        plan_name=plan_name
    )

    plan_variant = (
        " | ".join(variants)
        if variants
        else None
    )

    # --------------------------------------------------------
    # ID fallback
    # --------------------------------------------------------

    if not document_id:

        print(
            f"WARNING: no internal ID found: "
            f"{file_path.name}"
        )

        # Filename used ONLY as emergency fallback
        document_id = file_path.stem

    # --------------------------------------------------------
    # Sections
    # --------------------------------------------------------

    sections = split_into_sections(text)

    records = []

    global_chunk_number = 0

    for section_index, section in enumerate(
        sections,
        start=1
    ):

        section_name = section["section"]
        section_text = section["text"]

        section_chunks = chunk_text(
            section_text
        )

        for local_chunk_number, chunk in enumerate(
            section_chunks,
            start=1
        ):

            global_chunk_number += 1

            # Internal document ID + sequential chunk ID
            chunk_id = (
                f"{document_id}_chunk_"
                f"{global_chunk_number:04d}"
            )

            metadata = {

                "document_id": document_id,

                "chunk_id": chunk_id,

                "plan_name": plan_name,

                "state": state,

                "effective_date": effective_date,

                "form_number": form_number,

                "product_type": product_type,

                "plan_variant": plan_variant,

                "section": section_name,

                "section_index": section_index,

                "chunk_index": global_chunk_number,

                "source_file": file_path.name,
            }

            embedding_text = build_embedding_text(
                chunk_text_value=chunk,
                metadata=metadata
            )

            record = {

                # Azure Search-friendly unique ID
                "id": chunk_id,

                "document_id": document_id,

                "chunk_id": chunk_id,

                "plan_name": plan_name,

                "state": state,

                "effective_date": effective_date,

                "form_number": form_number,

                "product_type": product_type,

                "plan_variant": plan_variant,

                "section": section_name,

                "section_index": section_index,

                "chunk_index": global_chunk_number,

                "source_file": file_path.name,

                # Original text for citations / LLM response
                "text": chunk,

                # Text used for vector embedding
                "embedding_text": embedding_text,
            }

            records.append(record)

    return records


