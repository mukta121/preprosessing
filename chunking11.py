def extract_state(text: str) -> Optional[str]:
    """
    Look primarily near the top because state is normally
    part of the Schedule of Benefits heading.
    """

    top_text = text[:5000].upper()

    for state_upper, normalized_state in STATE_PATTERNS.items():

        if re.search(
            rf"\b{re.escape(state_upper)}\b",
            top_text
        ):
            return normalized_state

    return None


