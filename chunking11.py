# 11. PRODUCT TYPE
# ============================================================

def extract_product_type(
    text: str,
    plan_name: Optional[str] = None
) -> str:
    """
    Product type is primarily inferred from plan title.

    Examples:

    BEST BUY HMO 4000 - FLEX
        -> HMO

    NATIONAL ACCESS EPO HSA
        -> EPO

    BEST BUY HSA PPO
        -> PPO

    Explorer POS
        -> POS

    Pediatric Dental Rider - HMO
        -> Pediatric Dental

    VisionCare
        -> Vision
    """

    searchable = (
        (plan_name or "") +
        "\n" +
        text[:5000]
    ).upper()

    for product_type, patterns in PRODUCT_PATTERNS:

        for pattern in patterns:

            if re.search(
                pattern,
                searchable,
                flags=re.IGNORECASE
            ):
                return product_type

    return "UNKNOWN"


# ============================================================
# 12. PLAN VARIANT EXTRACTION
# ============================================================

def extract_plan_variants(
    text: str,
    plan_name: Optional[str]
) -> List[str]:

    searchable = (
        (plan_name or "") +
        "\n" +
        text[:3000]
    ).upper()

    found = []

    # Check more specific variants first
    ordered_items = sorted(
        PLAN_VARIANT_PATTERNS.items(),
        key=lambda x: max(len(p) for p in x[1]),
        reverse=True
    )

    for variant, patterns in ordered_items:

        for pattern in patterns:

            if re.search(
                pattern,
                searchable,
                flags=re.IGNORECASE
            ):

                if variant not in found:
                    found.append(variant)

                break

    # Avoid duplicate semantics
    if "Flex Plus" in found and "Flex" in found:
        found.remove("Flex")

    return found


