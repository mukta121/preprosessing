# 10. PLAN TITLE / PLAN NAME
# ============================================================

def remove_markdown_markup(line: str) -> str:

    line = line.strip()

    # Markdown heading
    line = re.sub(r"^#+\s*", "", line)

    # HTML comment
    line = re.sub(
        r"<!--.*?-->",
        "",
        line
    )

    return line.strip()


def extract_plan_name(text: str) -> Optional[str]:
    """
    Extract the plan name from the opening section.

    Typical examples:

    Schedule of Benefits
    Harvard Pilgrim Health Care, Inc.
    BEST BUY HMO 4000 - FLEX
    MASSACHUSETTS

    or:

    # Schedule of Benefits Harvard Pilgrim Health Care, Inc.
      NATIONAL ACCESS EPO HSA MASSACHUSETTS

    or:

    Pediatric Dental Rider - HMO
    Harvard Pilgrim Health Care, Inc.
    MAINE
    """

    lines = [
        remove_markdown_markup(x)
        for x in text.splitlines()
    ]

    lines = [
        x for x in lines
        if x
    ]

    # Remove known metadata/header lines
    useful = []

    for line in lines[:30]:

        upper = line.upper()

        if upper == "DOCUMENT TEXT":
            continue

        if upper.startswith("ID:"):
            continue

        if upper.startswith(".ID:"):
            continue

        if upper.startswith("DATE:"):
            continue

        if "PAGEHEADER=" in upper:
            continue

        if upper == "X":
            continue

        useful.append(line)

    if not useful:
        return None

    # --------------------------------------------------------
    # Find Schedule of Benefits
    # --------------------------------------------------------

    for i, line in enumerate(useful):

        upper = line.upper()

        if "SCHEDULE OF BENEFITS" in upper:

            after = re.sub(
                r"(?i)^SCHEDULE\s+OF\s+BENEFITS\s*",
                "",
                line
            ).strip()

            candidate_lines = []

            if after:
                candidate_lines.append(after)

            # Capture following title lines.
            for nxt in useful[i + 1:i + 6]:

                nxt_upper = nxt.upper()

                # Stop when actual narrative begins
                if any([
                    nxt_upper.startswith("PLEASE NOTE"),
                    nxt_upper.startswith("IMPORTANT INFORMATION"),
                    nxt_upper.startswith("THIS SCHEDULE"),
                    nxt_upper.startswith("THIS PLAN"),
                    nxt_upper.startswith("SERVICES ARE"),
                    nxt_upper.startswith("COVERAGE UNDER"),
                    nxt_upper.startswith("THE PEDIATRIC"),
                ]):
                    break

                candidate_lines.append(nxt)

            candidate = " ".join(candidate_lines).strip()

            if candidate:
                return clean_plan_name(candidate)

    # --------------------------------------------------------
    # Dental / Vision can sometimes not have SOB
    # --------------------------------------------------------

    for i, line in enumerate(useful[:10]):

        if re.search(
            r"(?i)\b("
            r"PEDIATRIC\s+DENTAL|"
            r"DENTAL\s+RIDER|"
            r"VISIONCARE|"
            r"MEDICARE\s+ENHANCE"
            r")\b",
            line
        ):

            candidate = " ".join(
                useful[i:i + 4]
            )

            return clean_plan_name(candidate)

    return clean_plan_name(useful[0])


def clean_plan_name(plan_name: str) -> str:
    """
    Removes state name from end of plan title while
    retaining useful insurer/product name.
    """

    plan_name = normalize_whitespace(
        plan_name.replace("\n", " ")
    )

    # Remove state words at end
    for state in STATE_PATTERNS:

        plan_name = re.sub(
            rf"\b{re.escape(state)}\b\s*$",
            "",
            plan_name,
            flags=re.IGNORECASE
        ).strip()

    return plan_name or None


