# 7. EFFECTIVE DATE
# ============================================================

def extract_effective_date(text: str) -> Optional[str]:
    """
    Examples:
        DATE: 01/01/2020
        DATE: 07/01/2012
    """

    patterns = [
        r'(?im)^\s*DATE\s*:\s*(\d{1,2}/\d{1,2}/\d{4})',
        r'\bDATE\s*:\s*(\d{1,2}/\d{1,2}/\d{4})',
    ]

    for pattern in patterns:

        match = re.search(pattern, text)

        if match:
            return match.group(1)

    return None


