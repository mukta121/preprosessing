# 10. DOCUMENT ID EXTRACTION
# ============================================================

def extract_document_id(
    md_text: str,
    source_path: Path
) -> str:

    patterns = [

        # Example:
        # <!-- PageHeader="ID: MD0000005930" -->

        r'(?i)PageHeader=.*?\bID\s*[:#]?\s*([A-Z]{1,5}\d{5,})',

        # ID: MD0000005930

        r'(?im)^\s*ID\s*[:#]?\s*([A-Z]{1,5}\d{5,})\s*$',

        # Generic standalone ID

        r'\b(MD\d{6,})\b',

        r'\b(DN\d{6,})\b',

        r'\b(ID\d{6,})\b',

    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            md_text
        )

        if match:

            return match.group(1).strip()

    # fallback to filename

    filename_match = re.search(
        r'([A-Za-z]{1,5}\d{5,})',
        source_path.stem
    )

    if filename_match:
        return filename_match.group(1)

    return source_path.stem


