# 25. TABLE QUALITY VALIDATION
# ============================================================

def validate_table(
    headers: List[str],
    rows: List[Dict[str, Any]],
    column_count: int
) -> Dict[str, Any]:

    issues = []

    score = 1.0

    if column_count <= 1:

        issues.append(
            "Table contains fewer than 2 columns."
        )

        score -= 0.30

    if not any(headers):

        issues.append(
            "No header row detected."
        )

        score -= 0.20

    if not rows:

        issues.append(
            "No data rows detected."
        )

        score -= 0.40

    benefit_table = looks_like_benefit_table(
        headers
    )

    if benefit_table:

        for row in rows:

            if (
                row.get("row_type")
                == "benefit"
                and
                not row.get("benefit")
            ):

                issues.append(
                    f"Missing benefit value at source row "
                    f"{row.get('source_row_index')}."
                )

                score -= 0.05

    score = max(
        0.0,
        min(
            score,
            1.0
        )
    )

    status = (
        "passed"
        if score >= 0.90
        else
        "review"
    )

    return {

        "validation_status":
            status,

        "quality_score":
            round(
                score,
                3
            ),

        "requires_review":
            status != "passed",

        "issues":
            issues
    }


