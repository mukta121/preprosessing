# 12. BUILD EMPTY GRID
# ============================================================

def create_grid(
    rows: int,
    columns: int
) -> List[List[Optional[Dict[str, Any]]]]:

    return [
        [None for _ in range(columns)]
        for _ in range(rows)
    ]


