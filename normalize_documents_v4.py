# 29. BENEFIT TABLE -> NORMALIZED MARKDOWN
# ============================================================

def benefit_table_to_markdown(
    table: Dict[str, Any]
) -> str:

    output = []

    output.append(
        f"## Table {table['table_id']}"
    )

    output.append("")

    if table.get("page_number"):

        output.append(
            f"Page: {table['page_number']}"
        )

        output.append("")

    output.append(
        "| Category | Benefit | In-Network | Out-of-Network |"
    )

    output.append(
        "|---|---|---|---|"
    )

    for row in table.get(
        "rows",
        []
    ):

        if row.get(
            "row_type"
        ) != "benefit":

            continue

        category = markdown_escape(
            row.get(
                "category"
            )
        )

        benefit = markdown_escape(
            row.get(
                "benefit"
            )
        )

        in_network = markdown_escape(
            row.get(
                "in_network"
            )
        )

        out_network = markdown_escape(
            row.get(
                "out_of_network"
            )
        )

        output.append(
            f"| {category} "
            f"| {benefit} "
            f"| {in_network} "
            f"| {out_network} |"
        )

    output.append("")

    output.append(
        f"Validation: "
        f"{table.get('validation_status')}"
    )

    output.append(
        f"Quality Score: "
        f"{table.get('quality_score')}"
    )

    return "\n".join(
        output
    )


# ============================================================
# 30. GENERIC TABLE -> MARKDOWN
# ============================================================

def generic_table_to_markdown(
    table: Dict[str, Any]
) -> str:

    rows = table.get(
        "rows",
        []
    )

    headers = table.get(
        "headers",
        []
    )

    output = [

        f"## Table {table['table_id']}",

        ""
    ]

    if table.get("page_number"):

        output.extend([

            f"Page: {table['page_number']}",

            ""
        ])

    if not headers:

        return "\n".join(
            output
        )

    output.append(
        "| "
        +
        " | ".join(
            markdown_escape(x)
            for x in headers
        )
        +
        " |"
    )

    output.append(
        "|"
        +
        "|".join(
            "---"
            for _ in headers
        )
        +
        "|"
    )

    for row in rows:

        values = row.get(
            "values",
            []
        )

        values = (
            values
            +
            [""] * len(headers)
        )[:len(headers)]

        output.append(
            "| "
            +
            " | ".join(
                markdown_escape(x)
                for x in values
            )
            +
            " |"
        )

    return "\n".join(
        output
    )


# ============================================================
# 31. ALL TABLES -> MARKDOWN
# ============================================================

def normalized_tables_to_markdown(
    tables: List[Dict[str, Any]]
) -> str:

    sections = []

    for table in tables:

        if table.get(
            "is_benefit_table"
        ):

            md = benefit_table_to_markdown(
                table
            )

        else:

            md = generic_table_to_markdown(
                table
            )

        sections.append(
            md
        )

    return (
        "\n\n"
        "----------------------------------------\n\n"
        .join(
            sections
        )
    )


