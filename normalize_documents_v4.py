# 33. FIND CORRESPONDING JSON
# ============================================================

def find_json_file(
    md_path: Path
) -> Optional[Path]:

    stem = md_path.stem

    candidate = (
        md_path.parent
        /
        f"{stem}.json"
    )

    if candidate.exists():
        return candidate

    # Sometimes:
    #
    # MD0000005930.md
    # MD0000005930_result.json

    candidates = list(
        md_path.parent.glob(
            f"{stem}*.json"
        )
    )

    if candidates:

        return candidates[0]

    return None


# ============================================================
# 34. IGNORE TABLE.MD FILES AS PRIMARY DOCUMENTS
# ============================================================

def is_table_markdown(
    path: Path
) -> bool:

    name = path.name.lower()

    return (
        ".table.md" in name
        or
        "_table.md" in name
        or
        "tables.md" in name
    )


# ============================================================
# 35. PROCESS SINGLE DOCUMENT
# ============================================================

def process_document(
    md_path: Path
) -> None:

    print(
        "\n=================================================="
    )

    print(
        f"Processing: {md_path.name}"
    )

    json_path = find_json_file(
        md_path
    )

    if json_path is None:

        print(
            "  SKIPPED: matching JSON not found."
        )

        return


    # --------------------------------------------------------
    # READ MARKDOWN
    # --------------------------------------------------------

    md_text = md_path.read_text(

        encoding="utf-8",

        errors="ignore"
    )


    document_id = extract_document_id(

        md_text,

        md_path
    )


    print(
        f"  document_id: {document_id}"
    )


    # --------------------------------------------------------
    # CLEAN MARKDOWN
    # --------------------------------------------------------

    cleaned_text = clean_document_markdown(
        md_text
    )


    # --------------------------------------------------------
    # READ AZURE JSON
    # --------------------------------------------------------

    with open(
        json_path,
        "r",
        encoding="utf-8"
    ) as f:

        raw_json = json.load(
            f
        )


    analyze_result = get_analyze_result(
        raw_json
    )


    # --------------------------------------------------------
    # NORMALIZE TABLES
    # --------------------------------------------------------

    tables = normalize_tables(

        analyze_result,

        document_id
    )


    print(
        f"  tables found: {len(tables)}"
    )


    for table in tables:

        print(
            "   ",
            table["table_id"],
            "| page:",
            table.get("page_number"),
            "| quality:",
            table.get("quality_score"),
            "| status:",
            table.get("validation_status")
        )


    # --------------------------------------------------------
    # OUTPUT DIRECTORY
    # --------------------------------------------------------

    document_folder = (

        OUTPUT_FOLDER
        /
        document_id
    )

    document_folder.mkdir(

        parents=True,

        exist_ok=True
    )


    # --------------------------------------------------------
    # NORMALIZED CLEAN DOCUMENT
    # --------------------------------------------------------

    cleaned_md_path = (

        document_folder
        /
        f"{document_id}_clean_normalized.md"
    )


    cleaned_md_path.write_text(

        cleaned_text,

        encoding="utf-8"
    )


    # --------------------------------------------------------
    # NORMALIZED TABLE MARKDOWN
    # --------------------------------------------------------

    normalized_tables_md = (
        normalized_tables_to_markdown(
            tables
        )
    )


    table_md_path = (

        document_folder
        /
        f"{document_id}_normalized_tables.md"
    )


    table_md_path.write_text(

        normalized_tables_md,

        encoding="utf-8"
    )


    # --------------------------------------------------------
    # NORMALIZED JSON
    # --------------------------------------------------------

    normalized_json = create_normalized_json(

        document_id=document_id,

        source_md=md_path,

        source_json=json_path,

        cleaned_text=cleaned_text,

        tables=tables
    )


    normalized_json_path = (

        document_folder
        /
        f"{document_id}_normalized.json"
    )


    with open(
        normalized_json_path,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(

            normalized_json,

            f,

            indent=2,

            ensure_ascii=False
        )


    # --------------------------------------------------------
    # VALIDATION REPORT
    # --------------------------------------------------------

    review_tables = [

        table
        for table in tables

        if table.get(
            "requires_review"
        )
    ]


    validation_report = {

        "document_id":
            document_id,

        "total_tables":
            len(tables),

        "passed_tables":
            len(tables)
            -
            len(review_tables),

        "tables_requiring_review":
            [

                {

                    "table_id":
                        x["table_id"],

                    "page_number":
                        x.get(
                            "page_number"
                        ),

                    "quality_score":
                        x.get(
                            "quality_score"
                        ),

                    "issues":
                        x.get(
                            "issues",
                            []
                        )
                }

                for x in review_tables
            ]
    }


    validation_path = (

        document_folder
        /
        f"{document_id}_validation.json"
    )


    with open(
        validation_path,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(

            validation_report,

            f,

            indent=2,

            ensure_ascii=False
        )


    print(
        "  OUTPUT:"
    )

    print(
        f"    {cleaned_md_path.name}"
    )

    print(
        f"    {table_md_path.name}"
    )

    print(
        f"    {normalized_json_path.name}"
    )

    print(
        f"    {validation_path.name}"
    )


