# 26. NORMALIZE ONE TABLE
# ============================================================

def normalize_table(
    table: Dict[str, Any],
    document_id: str,
    table_number: int
) -> Dict[str, Any]:

    table_id = (
        f"{document_id}_table_"
        f"{table_number:04d}"
    )

    grid = reconstruct_table_grid(
        table
    )

    raw_rows = grid_to_rows(
        grid
    )

    if not raw_rows:

        return {

            "table_id":
                table_id,

            "document_id":
                document_id,

            "page_number":
                get_table_page_number(
                    table
                ),

            "headers":
                [],

            "rows":
                [],

            "validation_status":
                "review",

            "quality_score":
                0,

            "requires_review":
                True,

            "issues":
                [
                    "Table contained no reconstructed rows."
                ]
        }

    header_index = find_header_row(
        grid
    )

    raw_headers = raw_rows[
        header_index
    ]

    headers = [
        normalize_header_name(x)
        for x in raw_headers
    ]

    normalized_rows = []

    current_category = None

    data_rows = raw_rows[
        header_index + 1:
    ]

    for relative_index, raw_row in enumerate(
        data_rows,
        start=1
    ):

        row_index = (
            header_index
            +
            relative_index
        )

        row = simplify_merged_row(
            raw_row
        )

        if not any(row):
            continue

        # ----------------------------------------------------
        # CATEGORY ROW
        # ----------------------------------------------------

        if is_category_row(row):

            current_category = row[0]

            normalized_rows.append({

                "source_row_index":
                    row_index,

                "row_type":
                    "category",

                "category":
                    current_category,

                "benefit":
                    None,

                "in_network":
                    None,

                "out_of_network":
                    None,

                "values":
                    row
            })

            continue

        # ----------------------------------------------------
        # NORMAL BENEFIT ROW
        # ----------------------------------------------------

        benefit = (
            row[0]
            if len(row) >= 1
            else ""
        )

        in_network = (
            row[1]
            if len(row) >= 2
            else ""
        )

        out_network = (
            row[2]
            if len(row) >= 3
            else ""
        )

        normalized_rows.append({

            "source_row_index":
                row_index,

            "row_type":
                "benefit",

            "category":
                current_category,

            "benefit":
                benefit,

            "in_network":
                in_network,

            "out_of_network":
                out_network,

            "values":
                row
        })


    validation = validate_table(

        headers=headers,

        rows=normalized_rows,

        column_count=table.get(
            "columnCount",
            0
        )
    )


    result = {

        "table_id":
            table_id,

        "document_id":
            document_id,

        "page_number":
            get_table_page_number(
                table
            ),

        "row_count":
            table.get(
                "rowCount"
            ),

        "column_count":
            table.get(
                "columnCount"
            ),

        "header_row_index":
            header_index,

        "headers":
            headers,

        "is_benefit_table":
            looks_like_benefit_table(
                headers
            ),

        "bounding_regions":
            get_table_bounding_regions(
                table
            ),

        "rows":
            normalized_rows,

        **validation
    }

    return result


