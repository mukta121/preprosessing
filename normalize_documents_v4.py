# 13. NORMALIZE AZURE CELL
# ============================================================

def normalize_azure_cell(
    cell: Dict[str, Any]
) -> Dict[str, Any]:

    return {

        "content":
            normalize_spaces(
                cell.get("content", "")
            ),

        "row_index":
            cell.get("rowIndex", 0),

        "column_index":
            cell.get("columnIndex", 0),

        "row_span":
            cell.get("rowSpan", 1) or 1,

        "column_span":
            cell.get("columnSpan", 1) or 1,

        "kind":
            cell.get("kind", "content"),

        "bounding_regions":
            cell.get("boundingRegions", []),

        "spans":
            cell.get("spans", []),

        "elements":
            cell.get("elements", []),
    }


# ============================================================
# 14. RECONSTRUCT TABLE GRID
# ============================================================

def reconstruct_table_grid(
    table: Dict[str, Any]
) -> List[List[Optional[Dict[str, Any]]]]:

    row_count = table.get(
        "rowCount",
        0
    )

    column_count = table.get(
        "columnCount",
        0
    )

    grid = create_grid(
        row_count,
        column_count
    )

    for raw_cell in table.get(
        "cells",
        []
    ):

        cell = normalize_azure_cell(
            raw_cell
        )

        row_index = cell["row_index"]

        column_index = cell["column_index"]

        row_span = cell["row_span"]

        column_span = cell["column_span"]

        for r in range(
            row_index,
            min(
                row_index + row_span,
                row_count
            )
        ):

            for c in range(
                column_index,
                min(
                    column_index + column_span,
                    column_count
                )
            ):

                copied_cell = deepcopy(
                    cell
                )

                copied_cell["is_span_origin"] = (
                    r == row_index
                    and
                    c == column_index
                )

                grid[r][c] = copied_cell

    return grid


