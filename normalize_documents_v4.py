# 27. NORMALIZE ALL TABLES
# ============================================================

def normalize_tables(
    analyze_result: Dict[str, Any],
    document_id: str
) -> List[Dict[str, Any]]:

    tables = analyze_result.get(
        "tables",
        []
    )

    normalized = []

    for index, table in enumerate(
        tables,
        start=1
    ):

        normalized_table = normalize_table(

            table=table,

            document_id=document_id,

            table_number=index
        )

        normalized.append(
            normalized_table
        )

    return normalized


