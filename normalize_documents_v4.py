# 28. ESCAPE MARKDOWN CELL VALUE
# ============================================================

def markdown_escape(
    value: Optional[str]
) -> str:

    if value is None:
        return ""

    value = str(value)

    value = value.replace(
        "|",
        "\\|"
    )

    value = re.sub(
        r"\s+",
        " ",
        value
    )

    return value.strip()


