def normalize_line_endings(text: str) -> str:

    return (
        text
        .replace("\r\n", "\n")
        .replace("\r", "\n")
    )


def normalize_spaces(text: str) -> str:
    """
    Normalize spaces inside extracted cell values.
    """

    if text is None:
        return ""

    text = str(text)

    text = text.replace("\xa0", " ")

    text = re.sub(
        r"[ \t]+",
        " ",
        text
    )

    text = re.sub(
        r"\s*\n\s*",
        " ",
        text
    )

    return text.strip()


# ============================================================
# 4. REMOVE MARKDOWN LINKS
# ============================================================

def remove_markdown_links(text: str) -> str:

    return re.sub(
        r"\[([^\]]+)\]\((.*?)\)",
        r"\1",
        text
    )


# ============================================================
# 5. REMOVE REPEATED COMPANY HEADERS
# ============================================================

def remove_repeated_headers(text: str) -> str:

    patterns = [

        r"(?im)^\s*Harvard Pilgrim Health Care\s*$",

        r"(?im)^\s*Harvard Pilgrim Health Care,\s*Inc\.\s*$",

        r"(?im)^\s*Harvard Pilgrim Health Care of New England,\s*Inc\.\s*$",

    ]

    for pattern in patterns:

        text = re.sub(
            pattern,
            "",
            text
        )

    return text


# ============================================================
# 6. REMOVE IMMEDIATE DUPLICATE LINES
# ============================================================

def remove_duplicate_lines(text: str) -> str:

    lines = text.splitlines()

    output = []

    previous = None

    for line in lines:

        current = line.strip()

        if current == previous and current:
            continue

        output.append(line)

        previous = current

    return "\n".join(output)


# ============================================================
# 7. CLEAN EXCESS WHITESPACE
# ============================================================

def clean_whitespace(text: str) -> str:

    text = re.sub(
        r"\n{4,}",
        "\n\n\n",
        text
    )

    return text.strip() + "\n"


# ============================================================
# 8. CLEAN MARKDOWN DOCUMENT
# ============================================================

def clean_document_markdown(text: str) -> str:

    text = normalize_line_endings(text)

    text = remove_markdown_links(text)

    text = remove_repeated_headers(text)

    text = remove_duplicate_lines(text)

    text = clean_whitespace(text)

    return text


