# 32. CREATE NORMALIZED DOCUMENT JSON
# ============================================================

def create_normalized_json(
    document_id: str,
    source_md: Path,
    source_json: Path,
    cleaned_text: str,
    tables: List[Dict[str, Any]]
) -> Dict[str, Any]:

    passed = sum(

        1
        for table in tables

        if table.get(
            "validation_status"
        )
        == "passed"
    )

    review = len(tables) - passed

    return {

        "document_id":
            document_id,

        "source_file":
            source_md.name,

        "source_json":
            source_json.name,

        "document_text":
            cleaned_text,

        "table_count":
            len(tables),

        "table_validation_summary": {

            "passed":
                passed,

            "review":
                review
        },

        "tables":
            tables
    }


