# ============================================================
# 16. CONVERT GRID INTO SIMPLE ROWS
# ============================================================

def grid_to_rows(
    grid: List[List[Optional[Dict[str, Any]]]]
) -> List[List[str]]:

    rows = []

    for row in grid:

        values = [
            grid_value(cell)
            for cell in row
        ]

        rows.append(values)

    return rows


# ============================================================
# 17. DETECT HEADER ROW
# ============================================================

def is_header_row(
    grid_row: List[Optional[Dict[str, Any]]]
) -> bool:

    kinds = []

    for cell in grid_row:

        if cell:

            kinds.append(
                cell.get(
                    "kind",
                    ""
                )
            )

    header_kinds = {
        "columnHeader",
        "rowHeader",
        "stubHead"
    }

    return any(
        kind in header_kinds
        for kind in kinds
    )


# ============================================================
# 18. FIND PRIMARY HEADER ROW
# ============================================================

def find_header_row(
    grid: List[List[Optional[Dict[str, Any]]]]
) -> int:
    """
    Prefer Azure's explicit columnHeader information.

    Otherwise choose first non-empty row.
    """

    for index, row in enumerate(grid):

        if is_header_row(row):

            return index

    for index, row in enumerate(grid):

        values = [
            grid_value(cell)
            for cell in row
        ]

        if any(values):
            return index

    return 0


# ============================================================
# 19. NORMALIZE HEADER NAMES
# ============================================================

def normalize_header_name(
    value: str
) -> str:

    value_lower = value.lower()

    if "benefit" in value_lower:
        return "Benefit"

    if (
        "in-network" in value_lower
        or
        "in network" in value_lower
    ):
        return "In-Network"

    if (
        "out-of-network" in value_lower
        or
        "out of network" in value_lower
    ):
        return "Out-of-Network"

    return normalize_spaces(value)


# ============================================================
# 20. IDENTIFY STANDARD SOB TABLE
# ============================================================

def looks_like_benefit_table(
    headers: List[str]
) -> bool:

    normalized = " ".join(
        headers
    ).lower()

    has_benefit = (
        "benefit" in normalized
    )

    has_network = (
        "network" in normalized
    )

    return (
        has_benefit
        and
        has_network
    )


# ============================================================
# 21. DETECT CATEGORY ROW
# ============================================================

def is_category_row(
    row: List[str]
) -> bool:
    """
    Typical SOB category row:

        Ambulance and Medical Transport | | |

    or Azure may duplicate the merged value across columns:

        Ambulance and Medical Transport |
        Ambulance and Medical Transport |
        Ambulance and Medical Transport

    Treat both as category rows.
    """

    cleaned = [
        normalize_spaces(x)
        for x in row
    ]

    non_empty = [
        x
        for x in cleaned
        if x
    ]

    if not non_empty:
        return False

    # Case 1:
    # First column populated, remaining empty

    if (
        cleaned[0]
        and
        all(
            not value
            for value in cleaned[1:]
        )
    ):
        return True

    # Case 2:
    # Same merged content propagated across all cells

    unique_values = set(
        non_empty
    )

    if (
        len(unique_values) == 1
        and
        len(cleaned) >= 2
    ):
        return True

    return False


# ============================================================
# 22. REMOVE DUPLICATED MERGED CELL VALUES
# ============================================================

def simplify_merged_row(
    row: List[str]
) -> List[str]:

    if not row:
        return row

    cleaned = [
        normalize_spaces(x)
        for x in row
    ]

    first = cleaned[0]

    if not first:
        return cleaned

    if all(
        (not x) or x == first
        for x in cleaned
    ):

        return [
            first
        ] + [
            ""
            for _ in cleaned[1:]
        ]

    return cleaned


