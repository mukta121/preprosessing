# 8. MAIN MARKDOWN CLEANING FUNCTION
# ============================================================

def clean_markdown(text):
    """
    Generic Markdown cleaning before RAG chunking/indexing.
    """

    # --------------------------------------------------------
    # Normalize line endings
    # --------------------------------------------------------

    text = text.replace(
        "\r\n",
        "\n"
    )

    text = text.replace(
        "\r",
        "\n"
    )

    # --------------------------------------------------------
    # Remove page/document artifacts
    # --------------------------------------------------------

    text = remove_page_artifacts(text)

    # --------------------------------------------------------
    # Remove known repeated document headers
    # --------------------------------------------------------

    text = remove_repeated_headers(text)

    # --------------------------------------------------------
    # Remove Markdown URLs but retain readable label
    # --------------------------------------------------------

    text = remove_markdown_links(text)

    # --------------------------------------------------------
    # Remove duplicate consecutive lines
    # --------------------------------------------------------

    text = remove_duplicate_lines(text)

    # --------------------------------------------------------
    # Clean whitespace
    # --------------------------------------------------------

    text = clean_whitespace(text)

    return text


