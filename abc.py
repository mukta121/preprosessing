# 10. PROCESS ONE FILE
# ============================================================

def process_single_file(file_path):
    """
    Process a single Markdown file.
    """

    print(
        f"\nProcessing: {file_path.name}"
    )

    # --------------------------------------------------------
    # Read original Markdown
    # --------------------------------------------------------

    text = file_path.read_text(
        encoding="utf-8",
        errors="ignore"
    )

    original_length = len(text)

    # --------------------------------------------------------
    # STEP 1:
    # Remove large boilerplate sections FIRST
    # --------------------------------------------------------

    text = remove_large_noise_sections(
        text
    )

    # --------------------------------------------------------
    # STEP 2:
    # General Markdown cleanup
    # --------------------------------------------------------

    cleaned_text = clean_markdown(
        text
    )

    # --------------------------------------------------------
    # STEP 3:
    # Validation
    # --------------------------------------------------------

    remaining_sections = validate_cleaning(
        cleaned_text
    )

    # --------------------------------------------------------
    # STEP 4:
    # Save cleaned Markdown
    # --------------------------------------------------------

    output_file = (
        DEST_DIR / file_path.name
    )

    output_file.write_text(
        cleaned_text,
        encoding="utf-8"
    )

    cleaned_length = len(cleaned_text)

    reduction = (
        original_length -
        cleaned_length
    )

    print(
        f"    Original chars : {original_length:,}"
    )

    print(
        f"    Cleaned chars  : {cleaned_length:,}"
    )

    print(
        f"    Removed chars  : {reduction:,}"
    )

    # --------------------------------------------------------
    # Validation reporting
    # --------------------------------------------------------

    if remaining_sections:

        print(
            "    WARNING: Some unwanted "
            "sections still remain:"
        )

        for section in remaining_sections:
            print(
                f"       - {section}"
            )

    else:

        print(
            "    Validation OK: "
            "noise sections removed"
        )

    print(
        f"    Saved -> {output_file}"
    )


