def process_files():
    """
    Process all Markdown files from SOURCE_DIR.
    """

    md_files = list(
        SOURCE_DIR.glob("*.md")
    )

    print(
        "=" * 70
    )

    print(
        "MARKDOWN CLEANING PIPELINE"
    )

    print(
        "=" * 70
    )

    print(
        f"Source folder      : {SOURCE_DIR}"
    )

    print(
        f"Destination folder : {DEST_DIR}"
    )

    print(
        f"Found {len(md_files)} Markdown files"
    )

    if len(md_files) == 0:

        print(
            "\nNo Markdown files found."
        )

        return

    successful = 0
    failed = 0

    for file_path in md_files:

        try:

            process_single_file(
                file_path
            )

            successful += 1

        except Exception as e:

            failed += 1

            print(
                f"\nERROR processing "
                f"{file_path.name}"
            )

            print(
                f"    {type(e).__name__}: {e}"
            )

    # --------------------------------------------------------
    # Final summary
    # --------------------------------------------------------

    print(
        "\n" + "=" * 70
    )

    print(
        "PROCESSING COMPLETED"
    )

    print(
        "=" * 70
    )

    print(
        f"Total files : {len(md_files)}"
    )

    print(
        f"Successful  : {successful}"
    )

    print(
        f"Failed      : {failed}"
    )

    print(
        f"\nCleaned files saved to:\n{DEST_DIR}"
    )


