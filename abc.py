# 3. REMOVE SPECIFIC DOCUMENT BANNERS / HEADERS
# ============================================================

def remove_repeated_headers(text):
    """
    Remove document-specific repeated headings or page banners.
    Add more patterns here when you discover common repeated noise.
    """

    repeated_header_patterns = [

        # Pediatric Dental Rider
        r"(?im)^#+\s*PEDIATRIC DENTAL RIDER.*$",

        # Best Buy HMO
        r"(?im)^#+\s*BEST BUY HMO.*$",

        # VisionCare
        r"(?im)^#+\s*VISIONCARE.*$",
    ]

    for pattern in repeated_header_patterns:

        text = re.sub(
            pattern,
            "",
            text
        )

    return text


# ============================================================
# 4. REMOVE ORGANIZATION / PAGE ARTIFACTS
# ============================================================

def remove_page_artifacts(text):
    """
    Remove recurring organization names or page artifacts.
    """

    patterns = [

        # Harvard Pilgrim Health Care variants
        r"(?im)^\s*Harvard Pilgrim Health Care\s*$",

        r"(?im)^\s*Harvard Pilgrim Health Care,\s*Inc\.\s*$",

        r"(?im)^\s*Harvard Pilgrim Health Care of New England,"
        r"\s*Inc\.\s*$",
    ]

    for pattern in patterns:

        text = re.sub(
            pattern,
            "",
            text
        )

    return text


# ============================================================
# 5. REMOVE MARKDOWN LINKS BUT KEEP LINK TEXT
# ============================================================

def remove_markdown_links(text):
    """
    Convert:
        [member portal](https://example.com)

    Into:
        member portal
    """

    text = re.sub(
        r"\[([^\]]+)\]\((.*?)\)",
        r"\1",
        text
    )

    return text


# ============================================================
# 6. REMOVE DUPLICATE CONSECUTIVE LINES
# ============================================================

def remove_duplicate_lines(text):
    """
    Remove immediately repeated duplicate lines.

    Example:

    Benefits
    Benefits

    becomes:

    Benefits
    """

    lines = text.splitlines()

    deduped = []

    for line in lines:

        current = line.strip()

        if not deduped:
            deduped.append(line)
            continue

        previous = deduped[-1].strip()

        if current != previous:
            deduped.append(line)

    return "\n".join(deduped)


