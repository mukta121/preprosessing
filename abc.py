# 2. REMOVE LARGE BOILERPLATE / NOISE SECTIONS
# ============================================================

def remove_large_noise_sections(text):
    """
    Remove large unwanted sections from Markdown documents.

    Sections currently removed:
    - Language Assistance Services
    - General Notice About Nondiscrimination
    - General List of Exclusions
    """

    # Normalize line endings
    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")

    sections_to_remove = [
        "Language Assistance Services",
        "General Notice About Nondiscrimination",
        "General List of Exclusions",
    ]

    for section in sections_to_remove:

        pattern = (
            rf"(?ims)"
            rf"^#+[ \t]*{re.escape(section)}[ \t]*$"
            rf".*?"
            rf"(?=^#+[ \t]+\S|\Z)"
        )

        text, count = re.subn(
            pattern,
            "",
            text
        )

        if count > 0:
            print(
                f"    Removed section "
                f"'{section}' -> {count} occurrence(s)"
            )

    return text


