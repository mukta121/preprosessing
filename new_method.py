# 9. TABLE SURROUNDING CONTEXT
# ============================================================

def context_before(
    text: str,
    position: int,
    chars: int = TABLE_CONTEXT_CHARS
) -> str:

    segment = text[
        max(0, position - chars):
        position
    ]

    # Remove HTML tags from context
    segment = BeautifulSoup(
        segment,
        "html.parser"
    ).get_text("\n")

    return clean_whitespace(segment)


def context_after(
    text: str,
    position: int,
    chars: int = TABLE_CONTEXT_CHARS
) -> str:

    segment = text[
        position:
        min(len(text), position + chars)
    ]

    segment = BeautifulSoup(
        segment,
        "html.parser"
    ).get_text("\n")

    return clean_whitespace(segment)


