HEADING_PATTERN = re.compile(
    r"^(#{1,6})\s+(.+?)\s*$",
    flags=re.MULTILINE
)


def extract_headings(markdown_text: str) -> List[Dict]:

    headings = []

    for match in HEADING_PATTERN.finditer(markdown_text):

        headings.append(
            {
                "position": match.start(),
                "level": len(match.group(1)),
                "text": clean_whitespace(match.group(2)),
            }
        )

    return headings


def section_at_position(
    headings: List[Dict],
    position: int
) -> Optional[str]:

    previous = [
        heading
        for heading in headings
        if heading["position"] <= position
    ]

    if not previous:
        return None

    return previous[-1]["text"]


