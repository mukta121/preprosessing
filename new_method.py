def token_jaccard(a: str, b: str) -> float:

    tokens_a = set(a.split())
    tokens_b = set(b.split())

    if not tokens_a or not tokens_b:
        return 0.0

    intersection = len(tokens_a & tokens_b)
    union = len(tokens_a | tokens_b)

    return intersection / union


def sequence_similarity(a: str, b: str) -> float:

    if not a or not b:
        return 0.0

    return SequenceMatcher(
        None,
        a,
        b,
    ).ratio()


def table_similarity(a: str, b: str) -> float:

    if not a or not b:
        return 0.0

    jaccard = token_jaccard(a, b)
    sequence = sequence_similarity(a, b)

    # Token overlap is more important than exact formatting/order.
    return (
        0.70 * jaccard
        + 0.30 * sequence
    )


def best_unused_match(
    source_text: str,
    candidates: List[Dict],
    used_indices: set,
    index_field: str,
) -> Tuple[Optional[int], float]:

    best_index = None
    best_score = -1.0

    for candidate in candidates:

        candidate_index = candidate[index_field]

        if candidate_index in used_indices:
            continue

        score = table_similarity(
            source_text,
            candidate["normalized_text"]
        )

        if score > best_score:
            best_score = score
            best_index = candidate_index

    return best_index, best_score


