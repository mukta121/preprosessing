def split_into_sections(text: str) -> List[Dict]:

    headings = list(
        HEADING_PATTERN.finditer(text)
    )

    if not headings:

        return [
            {
                "section": None,
                "level": None,
                "content": text,
            }
        ]

    sections = []

    # Content before first heading
    if headings[0].start() > 0:

        intro = text[:headings[0].start()].strip()

        if intro:
            sections.append(
                {
                    "section": "Document Introduction",
                    "level": 0,
                    "content": intro,
                }
            )

    for index, heading in enumerate(headings):

        start = heading.end()

        if index + 1 < len(headings):
            end = headings[index + 1].start()
        else:
            end = len(text)

        heading_text = clean_whitespace(
            heading.group(2)
        )

        content = text[start:end].strip()

        sections.append(
            {
                "section": heading_text,
                "level": len(heading.group(1)),
                "content": content,
            }
        )

    return sections


