def discover_documents(input_folder: Path) -> List[Dict]:

    documents = []

    for md_file in sorted(input_folder.glob("*.md")):

        name = md_file.name.lower()

        # Ignore table-only Markdown files
        if name.endswith(".table.md"):
            continue

        if name.endswith("_table.md"):
            continue

        base_name = md_file.stem

        json_file = input_folder / f"{base_name}.json"

        table_candidates = [
            input_folder / f"{base_name}.table.md",
            input_folder / f"{base_name}_table.md",
        ]

        table_md_file = None

        for candidate in table_candidates:
            if candidate.exists():
                table_md_file = candidate
                break

        if not json_file.exists():
            print(
                f"WARNING: JSON missing for {base_name}. "
                f"Skipping document."
            )
            continue

        if table_md_file is None:
            print(
                f"WARNING: Table Markdown missing for {base_name}. "
                f"Will continue using JSON tables."
            )

        documents.append(
            {
                "document_id": base_name,
                "body_md": md_file,
                "table_md": table_md_file,
                "json": json_file,
            }
        )

    return documents


