def is_markdown_separator(line: str) -> bool:

    line = line.strip()

    if "|" not in line:
        return False

    cells = [
        x.strip()
        for x in line.strip("|").split("|")
    ]

    if not cells:
        return False

    return all(
        re.fullmatch(r":?-{3,}:?", cell or "")
        for cell in cells
    )


def parse_markdown_row(line: str) -> List[str]:

    return [
        cell.strip()
        for cell in line.strip().strip("|").split("|")
    ]


def extract_markdown_tables(text: str) -> List[Dict]:

    if not text:
        return []

    lines = text.splitlines()

    tables = []

    i = 0

    while i < len(lines) - 1:

        current = lines[i]
        next_line = lines[i + 1]

        if (
            "|" in current
            and is_markdown_separator(next_line)
        ):

            block_lines = [
                current,
                next_line,
            ]

            j = i + 2

            while j < len(lines):

                line = lines[j]

                if "|" not in line:
                    break

                if not line.strip():
                    break

                block_lines.append(line)

                j += 1

            markdown = "\n".join(block_lines)

            header = parse_markdown_row(block_lines[0])

            rows = []

            for line in block_lines[2:]:
                rows.append(parse_markdown_row(line))

            flat_text = " ".join(
                header
                + [
                    cell
                    for row in rows
                    for cell in row
                ]
            )

            tables.append(
                {
                    "markdown_index": len(tables),
                    "markdown": markdown,
                    "header": header,
                    "rows": rows,
                    "text": flat_text,
                    "normalized_text": normalize_for_matching(flat_text),
                }
            )

            i = j

        else:
            i += 1

    return tables


