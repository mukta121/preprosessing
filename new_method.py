def get_json_table_page(table: Dict) -> Optional[int]:

    bounding_regions = (
        table.get("boundingRegions")
        or table.get("bounding_regions")
        or []
    )

    if bounding_regions:

        region = bounding_regions[0]

        return (
            region.get("pageNumber")
            or region.get("page_number")
        )

    return None


def extract_json_tables(json_data: Dict) -> List[Dict]:

    analyze_result = get_analyze_result(json_data)

    raw_tables = analyze_result.get("tables", [])

    tables = []

    for index, table in enumerate(raw_tables):

        cells = table.get("cells", [])

        parsed_cells = []

        max_row = 0
        max_col = 0

        for cell in cells:

            row_index = (
                cell.get("rowIndex")
                if "rowIndex" in cell
                else cell.get("row_index", 0)
            )

            col_index = (
                cell.get("columnIndex")
                if "columnIndex" in cell
                else cell.get("column_index", 0)
            )

            row_span = (
                cell.get("rowSpan")
                or cell.get("row_span")
                or 1
            )

            col_span = (
                cell.get("columnSpan")
                or cell.get("column_span")
                or 1
            )

            content = clean_whitespace(
                cell.get("content", "")
            )

            kind = (
                cell.get("kind")
                or cell.get("cellKind")
                or ""
            )

            parsed_cells.append(
                {
                    "row": row_index,
                    "column": col_index,
                    "row_span": row_span,
                    "column_span": col_span,
                    "content": content,
                    "kind": kind,
                }
            )

            max_row = max(max_row, row_index)
            max_col = max(max_col, col_index)

        rows = [
            [""] * (max_col + 1)
            for _ in range(max_row + 1)
        ]

        for cell in parsed_cells:

            r = cell["row"]
            c = cell["column"]

            if r < len(rows) and c < len(rows[r]):
                rows[r][c] = cell["content"]

        flat_text = " ".join(
            cell
            for row in rows
            for cell in row
            if cell
        )

        spans = table.get("spans", [])

        span_offset = None
        span_length = None

        if spans:

            span_offset = spans[0].get("offset")
            span_length = spans[0].get("length")

        page_number = get_json_table_page(table)

        tables.append(
            {
                "json_index": index,
                "page_number": page_number,
                "row_count": table.get(
                    "rowCount",
                    table.get("row_count", len(rows))
                ),
                "column_count": table.get(
                    "columnCount",
                    table.get(
                        "column_count",
                        max_col + 1
                    )
                ),
                "cells": parsed_cells,
                "rows": rows,
                "text": flat_text,
                "normalized_text": normalize_for_matching(flat_text),
                "span_offset": span_offset,
                "span_length": span_length,
                "raw_table": table,
            }
        )

    return tables


