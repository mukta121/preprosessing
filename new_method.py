def replace_html_with_placeholders(
    body_md: str,
    normalized_tables: List[Dict]
) -> str:

    replacements = []

    for table in normalized_tables:

        position = table.get("body_position")

        html_index = table.get("html_index")

        if position is None or html_index is None:
            continue

        replacements.append(table)

    # Need fresh HTML positions
    html_tables = extract_html_tables(body_md)

    replacement_map = {
        table["html_index"]: table["table_id"]
        for table in replacements
    }

    pieces = []

    last_position = 0

    for html_table in html_tables:

        start = html_table["start"]
        end = html_table["end"]
        index = html_table["html_index"]

        pieces.append(
            body_md[last_position:start]
        )

        if index in replacement_map:

            table_id = replacement_map[index]

            pieces.append(
                f"\n\n[TABLE: {table_id}]\n\n"
            )

        else:

            # Keep unmatched table instead of deleting data
            pieces.append(html_table["html"])

        last_position = end

    pieces.append(body_md[last_position:])

    return clean_whitespace(
        "".join(pieces)
    )


