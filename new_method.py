def clean_whitespace(text: str) -> str:
    """Normalize whitespace without changing content."""
    if not text:
        return ""

    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")

    # Remove trailing whitespace
    text = "\n".join(line.rstrip() for line in text.splitlines())

    # Collapse excessive blank lines
    text = re.sub(r"\n{4,}", "\n\n\n", text)

    return text.strip()


def normalize_for_matching(text: str) -> str:
    """
    Normalize text for table matching.

    Used only for comparison — not for the final indexed content.
    """

    if not text:
        return ""

    text = text.lower()

    # Decode common HTML entities indirectly through BeautifulSoup
    text = BeautifulSoup(text, "html.parser").get_text(" ")

    # Normalize whitespace
    text = re.sub(r"\s+", " ", text)

    # Remove most punctuation
    text = re.sub(r"[^a-z0-9%$.,:/\- ]+", " ", text)

    text = re.sub(r"\s+", " ", text)

    return text.strip()


def stable_hash(text: str, length: int = 10) -> str:
    return hashlib.md5(
        text.encode("utf-8", errors="ignore")
    ).hexdigest()[:length]


