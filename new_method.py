def process_document(files: Dict):

    document_id = files["document_id"]

    print()
    print("=" * 70)
    print(f"Processing: {document_id}")
    print("=" * 70)

    # --------------------------------------------------------
    # Read source files
    # --------------------------------------------------------

    body_md = files["body_md"].read_text(
        encoding="utf-8",
        errors="ignore"
    )

    body_md = clean_whitespace(body_md)

    if files["table_md"]:

        table_md_text = files["table_md"].read_text(
            encoding="utf-8",
            errors="ignore"
        )

    else:

        table_md_text = ""

    with open(
        files["json"],
        "r",
        encoding="utf-8"
    ) as f:

        json_data = json.load(f)

    # --------------------------------------------------------
    # Extract representations
    # --------------------------------------------------------

    html_tables = extract_html_tables(
        body_md
    )

    markdown_tables = extract_markdown_tables(
        table_md_text
    )

    json_tables = extract_json_tables(
        json_data
    )

    print(
        f"HTML tables      : {len(html_tables)}"
    )

    print(
        f"Markdown tables  : {len(markdown_tables)}"
    )

    print(
        f"JSON tables      : {len(json_tables)}"
    )

    # --------------------------------------------------------
    # Match all table representations
    # --------------------------------------------------------

    normalized_tables = build_normalized_tables(
        document_id=document_id,
        body_md=body_md,
        html_tables=html_tables,
        markdown_tables=markdown_tables,
        json_tables=json_tables,
    )

    # --------------------------------------------------------
    # Replace duplicate HTML table with table ID
    # --------------------------------------------------------

    normalized_text = replace_html_with_placeholders(
        body_md,
        normalized_tables
    )

    # --------------------------------------------------------
    # Final normalized object
    # --------------------------------------------------------

    normalized_document = {

        "document_id": document_id,

        "source_files": {
            "body_markdown":
                files["body_md"].name,

            "table_markdown":
                (
                    files["table_md"].name
                    if files["table_md"]
                    else None
                ),

            "document_intelligence_json":
                files["json"].name,
        },

        "body": normalized_text,

        "tables": normalized_tables,

        "statistics": {
            "html_table_count":
                len(html_tables),

            "markdown_table_count":
                len(markdown_tables),

            "json_table_count":
                len(json_tables),

            "normalized_table_count":
                len(normalized_tables),
        },
    }

    # --------------------------------------------------------
    # Save normalized JSON
    # --------------------------------------------------------

    OUTPUT_FOLDER.mkdir(
        parents=True,
        exist_ok=True
    )

    json_output = (
        OUTPUT_FOLDER
        / f"{document_id}.normalized.json"
    )

    with open(
        json_output,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            normalized_document,
            f,
            ensure_ascii=False,
            indent=2
        )

    # --------------------------------------------------------
    # Save normalized Markdown for inspection/debugging
    # --------------------------------------------------------

    md_output = (
        OUTPUT_FOLDER
        / f"{document_id}.normalized.md"
    )

    md_output.write_text(
        normalized_text,
        encoding="utf-8"
    )

    # --------------------------------------------------------
    # Chunk
    # --------------------------------------------------------

    text_chunks = create_text_chunks(
        document_id,
        normalized_text
    )

    table_chunks = create_table_chunks(
        document_id,
        normalized_tables
    )

    all_chunks = (
        text_chunks
        + table_chunks
    )

    all_chunks = add_chunk_links(
        all_chunks
    )

    print(
        f"Text chunks      : {len(text_chunks)}"
    )

    print(
        f"Table chunks     : {len(table_chunks)}"
    )

    print(
        f"Total chunks     : {len(all_chunks)}"
    )

    return normalized_document, all_chunks


