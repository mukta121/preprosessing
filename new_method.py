def split_long_text(
    text: str,
    max_chars: int,
    overlap_chars: int,
) -> List[str]:

    text = clean_whitespace(text)

    if len(text) <= max_chars:
        return [text] if text else []

    paragraphs = re.split(
        r"\n\s*\n",
        text
    )

    chunks = []

    current = ""

    for paragraph in paragraphs:

        paragraph = paragraph.strip()

        if not paragraph:
            continue

        proposed = (
            current
            + "\n\n"
            + paragraph
            if current
            else paragraph
        )

        if len(proposed) <= max_chars:

            current = proposed

        else:

            if current:
                chunks.append(current)

            # Very large paragraph
            if len(paragraph) > max_chars:

                start = 0

                while start < len(paragraph):

                    end = min(
                        start + max_chars,
                        len(paragraph)
                    )

                    chunk = paragraph[start:end]

                    chunks.append(chunk)

                    if end == len(paragraph):
                        break

                    start = max(
                        0,
                        end - overlap_chars
                    )

                current = ""

            else:

                # Carry trailing overlap from previous chunk
                if chunks and overlap_chars > 0:

                    overlap = chunks[-1][
                        -overlap_chars:
                    ]

                    current = (
                        overlap
                        + "\n\n"
                        + paragraph
                    )

                    if len(current) > max_chars:
                        current = paragraph

                else:
                    current = paragraph

    if current:
        chunks.append(current)

    return chunks


def create_text_chunks(
    document_id: str,
    normalized_text: str
) -> List[Dict]:

    sections = split_into_sections(
        normalized_text
    )

    chunks = []

    chunk_counter = 1

    for section in sections:

        section_name = section["section"]
        content = section["content"]

        pieces = split_long_text(
            content,
            MAX_TEXT_CHARS,
            TEXT_OVERLAP_CHARS,
        )

        for piece in pieces:

            if not piece.strip():
                continue

            chunk_id = (
                f"{document_id}_text_"
                f"{chunk_counter:05d}"
            )

            # Include section in searchable content
            if section_name:

                searchable_content = (
                    f"Section: {section_name}\n\n"
                    f"{piece}"
                )

            else:

                searchable_content = piece

            chunks.append(
                {
                    "chunk_id": chunk_id,
                    "document_id": document_id,

                    "chunk_type": "text",

                    "content_source": "document_body",

                    "section": section_name,

                    "page_number": None,

                    "table_id": None,

                    "content": searchable_content,

                    "metadata": {
                        "section_level": section["level"]
                    },
                }
            )

            chunk_counter += 1

    return chunks


# ============================================================
# 15. TABLE ROW CHUNKING
# ============================================================

def markdown_table_chunk(
    header: List[str],
    rows: List[List[str]]
) -> str:

    all_rows = [header] + rows

    return rows_to_markdown(all_rows)


def create_table_chunks(
    document_id: str,
    tables: List[Dict]
) -> List[Dict]:

    chunks = []

    counter = 1

    for table in tables:

        rows = table["json_rows"]

        if not rows:
            continue

        header = rows[0]

        body_rows = rows[1:]

        # A one-row table is still kept
        if not body_rows:

            row_groups = [[]]

        else:

            row_groups = [
                body_rows[i:i + MAX_TABLE_ROWS_PER_CHUNK]
                for i in range(
                    0,
                    len(body_rows),
                    MAX_TABLE_ROWS_PER_CHUNK
                )
            ]

        for group_number, group in enumerate(
            row_groups,
            start=1
        ):

            table_md = markdown_table_chunk(
                header,
                group
            )

            context_parts = []

            if table["section"]:

                context_parts.append(
                    f"Section: {table['section']}"
                )

            if table["preceding_context"]:

                context_parts.append(
                    "Context before table:\n"
                    + table["preceding_context"]
                )

            context_parts.append(
                "Table:\n"
                + table_md
            )

            if table["following_context"]:

                context_parts.append(
                    "Context after table:\n"
                    + table["following_context"]
                )

            content = "\n\n".join(
                context_parts
            )

            chunk_id = (
                f"{document_id}_table_"
                f"{counter:05d}"
            )

            chunks.append(
                {
                    "chunk_id": chunk_id,

                    "document_id": document_id,

                    "chunk_type": "table",

                    "content_source": "normalized_table",

                    "section": table["section"],

                    "page_number": table["page_number"],

                    "table_id": table["table_id"],

                    "table_part": group_number,

                    "content": content,

                    "metadata": {
                        "row_count": table["row_count"],
                        "column_count": table["column_count"],

                        "table_source": table["table_source"],

                        "html_match_score":
                            table["html_match_score"],

                        "markdown_match_score":
                            table["markdown_match_score"],
                    },
                }
            )

            counter += 1

    return chunks


# ============================================================
# 16. ADD PREVIOUS / NEXT CHUNK REFERENCES
# ============================================================

def add_chunk_links(chunks: List[Dict]) -> List[Dict]:

    for index, chunk in enumerate(chunks):

        if index > 0:
            chunk["previous_chunk_id"] = (
                chunks[index - 1]["chunk_id"]
            )
        else:
            chunk["previous_chunk_id"] = None

        if index < len(chunks) - 1:
            chunk["next_chunk_id"] = (
                chunks[index + 1]["chunk_id"]
            )
        else:
            chunk["next_chunk_id"] = None

    return chunks


