# 11. PROCESS ALL FILES
# ============================================================

def process_files():
    """
    Process all Markdown files in SOURCE_DIR.
    """

    md_files = list(
        SOURCE_DIR.glob("*.md")
    )

    print(
        "=" * 70
    )

    print(
        "MARKDOWN PREPROCESSING FOR RAG"
    )

    print(
        "=" * 70
    )

    print(
        f"\nSource directory:\n{SOURCE_DIR}"
    )

    print(
        f"\nDestination directory:\n{DEST_DIR}"
    )

    print(
        f"\nFound {len(md_files)} Markdown files."
    )

    if len(md_files) == 0:

        print(
            "\nNo Markdown files found."
        )

        return

    successful = 0
    failed = 0

    for file_path in md_files:

        try:

            process_single_file(
                file_path
            )

            successful += 1

        except Exception as e:

            failed += 1

            print(
                f"\nERROR processing: {file_path.name}"
            )

            print(
                f"    Error type: {type(e).__name__}"
            )

            print(
                f"    Error: {e}"
            )

    # ========================================================
    # FINAL SUMMARY
    # ========================================================

    print(
        "\n" + "=" * 70
    )

    print(
        "PROCESS COMPLETED"
    )

    print(
        "=" * 70
    )

    print(
        f"Total files : {len(md_files)}"
    )

    print(
        f"Successful  : {successful}"
    )

    print(
        f"Failed      : {failed}"
    )

    print(
        f"\nCleaned files saved to:\n{DEST_DIR}"
    )


# ============================================================
# 12. ENTRY POINT
# ============================================================

if __name__ == "__main__":

    process_files()
